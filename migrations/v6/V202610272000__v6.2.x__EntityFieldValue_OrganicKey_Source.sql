-- Migration: record where each EntityFieldValue and EntityOrganicKey row came from (#4535)
--
-- CodeGen writes value lists and organic keys from two places: CHECK constraints (value lists only)
-- and the additionalSchemaInfo config file. People also create both by hand. Until now the rows
-- looked the same whatever their origin, so CodeGen could not remove what the config file stopped
-- declaring without risking rows someone built by hand. The new Source column records the origin;
-- CodeGen stamps it on every row it writes and only ever retracts rows whose Source is 'Config'.
--
-- Backfill:
--   * EntityFieldValue rows on a field that has a column-level CHECK constraint become 'Check'.
--     CodeGen's CHECK pass is the only writer of value lists for such fields.
--   * Every other existing row, in both tables, becomes 'Manual' through the column default. The
--     origin of those rows cannot be told apart after the fact, and 'Manual' rows are never
--     retracted. CodeGen re-stamps a row as 'Config' when the config file still declares it.

ALTER TABLE ${flyway:defaultSchema}.EntityFieldValue
ADD Source NVARCHAR(20) NOT NULL
    CONSTRAINT DF_EntityFieldValue_Source DEFAULT 'Manual'
    CONSTRAINT CK_EntityFieldValue_Source CHECK (Source IN ('Check', 'Config', 'Manual'));

ALTER TABLE ${flyway:defaultSchema}.EntityOrganicKey
ADD Source NVARCHAR(20) NOT NULL
    CONSTRAINT DF_EntityOrganicKey_Source DEFAULT 'Manual'
    CONSTRAINT CK_EntityOrganicKey_Source CHECK (Source IN ('Config', 'Manual'));
GO

