-- v6.3.x — Every query has an owner (follow-up to #6815)
--
-- WHY. #6815 lets any user save a query as a draft: the UI role holds Create on
-- MJ: Queries, and approving one needs the 'Queries: Approve' authorization. It
-- gave the UI role no Update or Delete, because nothing on a query said whose it
-- was, so granting either would have let a UI user change or remove anyone's
-- query. A UI user could not fix their own draft, and a list's unused draft could
-- not be cleaned up.
--
-- WHAT.
--   1. Query.OwnerUserID, NOT NULL, references User. Existing queries get the user
--      who created them, read from the Create row in Record Changes (MJ: Queries
--      tracks record changes), or the system user when there is no such row.
--   2. A row-level-security filter, "UI: Own Queries":
--
--          (OwnerUserID = '{{UserID}}')
--
--      The UI role's MJ: Queries permission row (metadata/entity-permissions/
--      .query-authoring-permissions.json) binds it to Create, Update and Delete,
--      as V202611111345 does for MJ: Projects. Read stays unfiltered. Developer
--      and Integration are unchanged and stay unfiltered.
--
-- WHAT A UI-ONLY USER CAN THEN DO. Every save is checked against the filter on the
-- stored row and on the row as it will be written, so a UI-only user creates a
-- query only as its owner, and updates or deletes only queries they own. The
-- server (MJQueryEntityServer) sets the owner of a new query to the user saving
-- it, lets only a holder of 'Queries: Approve' change an existing query's owner,
-- and saves a non-holder's change to an Approved query's definition as Pending.
--
-- WHY THE FILTER IS IN A MIGRATION. `MJ: Row Level Security Filters` grants Create
-- to no role, so `mj sync push` cannot write it; V202611111345 adds its filter the
-- same way.
-- ============================================================================

