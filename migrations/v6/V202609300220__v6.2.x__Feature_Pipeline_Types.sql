-- =====================================================================================
-- Feature Pipeline Types
--
-- A Knowledge Hub Feature Pipeline (an MJ: Record Processes row with WorkType 'Infer' and a
-- DataFeatureSpec) turns each record's context into output values. Until now there was one way to
-- do that: an LLM prompt. This table is the catalog of pipeline types. Each type names the driver
-- class (a BaseFeaturePipelineDriver subclass, resolved through the ClassFactory) that computes a
-- record's outputs, so a new type is a row plus a registered class, with no code switch.
--
-- A pipeline names its type in its spec (DataFeatureSpec.PipelineType), not in a Record Processes
-- column: the other work types have no pipeline type. A spec without one is an LLM pipeline.
--
-- Plan: plans/typed-decision-models.md, Task 5.1.
-- =====================================================================================

