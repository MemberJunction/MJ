-- DuplicateRun.EntityDocumentID (v6.2.x)
-- =============================================================================
-- A duplicate run now records the Entity Document it ran with. Until now a run carried only its
-- EntityID, and the server chose the entity's newest active Record Duplicate document itself, so
-- when an entity had more than one, the document picked in the Duplicates tab was ignored and
-- nothing recorded which document produced a run's matches.
--
-- Steps:
--   1. Add the column, nullable.
--   2. Backfill existing runs from their entity's documents: a 'Record Duplicate' document first,
--      then an Active one, then the most recently updated.
--   3. Delete runs whose entity has no Entity Document at all, with their details and matches.
--      They cannot satisfy the NOT NULL below, and with no document their results cannot be
--      reproduced or traced. Most installs have no such rows.
--   4. Add the foreign key and make the column NOT NULL, so every run names its document.
--
-- An Entity Document with history (duplicate runs, synced vectors) cannot be deleted: nothing
-- cascades from it (metadata/entities/.entity-cascade-deletes-entity-documents.json turns
-- CascadeDeletes off for MJ: Entity Documents), so the foreign keys refuse the delete before
-- anything is removed and the history stays as an audit trail. A document that is no longer
-- needed is set Inactive instead.
--
-- DDL, the backfill the NOT NULL needs, and extended properties only. The FK index, base view,
-- stored procedures and EntityField metadata are produced by CodeGen and appended below the
-- CodeGen banner.
-- =============================================================================

-- 1. Column
ALTER TABLE ${flyway:defaultSchema}.DuplicateRun ADD EntityDocumentID UNIQUEIDENTIFIER NULL;
GO

-- 2. Backfill
UPDATE dr
SET EntityDocumentID = (
    SELECT TOP 1 ed.ID
    FROM ${flyway:defaultSchema}.EntityDocument ed
    LEFT JOIN ${flyway:defaultSchema}.EntityDocumentType edt ON edt.ID = ed.TypeID
    WHERE ed.EntityID = dr.EntityID
    ORDER BY
        CASE WHEN edt.Name = 'Record Duplicate' THEN 0 ELSE 1 END,
        CASE WHEN ed.Status = 'Active' THEN 0 ELSE 1 END,
        ed.__mj_UpdatedAt DESC
)
FROM ${flyway:defaultSchema}.DuplicateRun dr
WHERE dr.EntityDocumentID IS NULL;
GO

-- 3. Runs that cannot be backfilled: their entity has no Entity Document
DELETE drdm
FROM ${flyway:defaultSchema}.DuplicateRunDetailMatch drdm
INNER JOIN ${flyway:defaultSchema}.DuplicateRunDetail drd ON drd.ID = drdm.DuplicateRunDetailID
INNER JOIN ${flyway:defaultSchema}.DuplicateRun dr ON dr.ID = drd.DuplicateRunID
WHERE dr.EntityDocumentID IS NULL;

DELETE drd
FROM ${flyway:defaultSchema}.DuplicateRunDetail drd
INNER JOIN ${flyway:defaultSchema}.DuplicateRun dr ON dr.ID = drd.DuplicateRunID
WHERE dr.EntityDocumentID IS NULL;

DELETE FROM ${flyway:defaultSchema}.DuplicateRun
WHERE EntityDocumentID IS NULL;
GO

