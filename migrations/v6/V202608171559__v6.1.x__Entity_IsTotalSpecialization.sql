-- =============================================================================
-- Entity.IsTotalSpecialization — the COMPLETENESS constraint for ISA
-- specialization (total vs. partial), the pair to AllowMultipleSubtypes.
-- =============================================================================
--
-- WHAT THIS ADDS. Enhanced-ER (EER) specialization carries two independent
-- constraints, and MemberJunction modelled only one of them:
--
--   * Disjointness — may a superclass entity be a member of more than one
--     subclass?  Already modelled by Entity.AllowMultipleSubtypes
--     (0 = disjoint, 1 = overlapping).
--   * Completeness — MUST every superclass entity belong to some subclass?
--     This column adds it: 0 = partial specialization (a superclass row may
--     exist without a subtype), 1 = total specialization (every superclass row
--     must belong to a subtype).
--
-- The flag lives on the PARENT (superclass) entity, symmetric with
-- AllowMultipleSubtypes. Together the two express the four canonical
-- specialization kinds (disjoint/overlapping x total/partial).
--
-- HOW IT IS ENFORCED. When an entity is a parent type with
-- IsTotalSpecialization = 1, the entity-layer save refuses to persist a
-- STANDALONE superclass record — a direct parent save with no subclass row for
-- its primary key — and directs the caller to create the record through a
-- subclass, which writes the superclass and subclass rows together in one
-- transaction. Subclass-initiated (leaf-chain) saves are unaffected. This is
-- well-defined for DISJOINT specialization (a single required subtype); a
-- parent that permits overlapping subtypes has no single "the" subtype to
-- require, so the constraint does not apply there.
--
-- ADDITIVE ON PURPOSE. The default is 0 (partial), which is the pre-feature
-- behaviour for every existing entity: a superclass record may stand alone.
-- No existing row changes meaning, and nothing new is enforced until an entity
-- opts in.
-- =============================================================================

