-- =====================================================================================
-- Content pipeline retry schedule: a Retry outcome waits, with backoff, instead of failing
--
-- A pipeline stage answers a passing failure (a provider's rate limit, a timeout, a
-- stage out of its time budget) with a Retry outcome. Until now the pipeline committed
-- every outcome but Complete and Skipped as the stage's 'Failed' status, and no stage's
-- readiness filter selects 'Failed', so a record a stage asked to try again stayed
-- failed for good.
--
-- A Retry now leaves the record's status ready and sets a wait instead. These two
-- columns hold it, on both entities the pipeline's stages run over:
--   RetryCount  Retry outcomes in a row since a stage last settled the record; each one
--               doubles the wait (Options.Tuning RetryBackoffBaseMs, RetryBackoffMaxMs).
--   RetryAfter  The earliest time a stage may pick the record up again. Every pipeline
--               Record Process's ScopeFilter skips the record until then.
-- A commit that settles the record (Complete, Skipped, Failed), and new content that
-- resets the downstream stages, clear both.
--
-- The schedule is per record, not per stage: when two stages are both ready on a Content
-- Item (Tag and Segment), a Retry from one delays the other until the wait has passed.
-- =====================================================================================

ALTER TABLE ${flyway:defaultSchema}.ContentItem
ADD RetryCount INT NOT NULL
        CONSTRAINT DF_ContentItem_RetryCount DEFAULT 0
        CONSTRAINT CK_ContentItem_RetryCount CHECK (RetryCount >= 0),
    RetryAfter DATETIMEOFFSET NULL;
GO

