-- Two more ways for a contribution to sit among a section's content.
--
-- ReplacesSectionKeys: a panel can stand in for several blocks at once, not only one. It is a
-- JSON array of section keys, the same shape as ReplacesFieldNames and FormChromeRule.JoinFields.
-- Every key named must be in one tab, and the panel draws in the place of the first of them.
-- ReplacesSectionKey stays for the single-block and whole-tab claims already written.
--
