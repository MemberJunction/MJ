    [LastLoginAt] DATETIMEOFFSET NULL,
    CONSTRAINT [PK_UserExternalIdentity] PRIMARY KEY ([ID]),
    CONSTRAINT [FK_UserExternalIdentity_User] FOREIGN KEY ([UserID]) REFERENCES [${flyway:defaultSchema}].[User]([ID]),
