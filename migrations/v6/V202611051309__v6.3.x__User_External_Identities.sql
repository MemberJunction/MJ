-- ============================================================================
-- User External Identities
-- ============================================================================
-- Binds a User to an identity-provider account by the token's issuer and
-- subject. A verified login used to reach its User record by email alone, so a
-- USER_EMAIL_MAP entry, an email change at the provider, or a second record
-- carrying the same address sent the login to whichever record matched. The
-- server now looks the login up here first and falls back to email only when
-- no binding exists, saving one on that first match.
--
-- One User can hold several bindings, one per provider account. The pair
-- (Issuer, Subject) is unique: one provider account belongs to one User.
--
-- Additive only. CodeGen owns the entity, view, procedures and generated
-- classes. PostgreSQL counterpart is produced by the release build.
-- ============================================================================

