/* ============================================================================
   IdentityClaim — de-duplicate EntityRelationship rows
   v6.1.x

   V202609091200__v6.1.x__IdentityClaim_Metadata_Tail.sql supplies the four
   EntityRelationship rows for MJ: Identity Claims, guarded on PRIMARY KEY:

       IF NOT EXISTS (SELECT 1 FROM EntityRelationship WHERE [ID] = 'dd73e538-…')

   Those IDs were generated by the CodeGen run that authored that migration. But
   the whole premise of the gap is that these rows already exist on every
   DEVELOPER database — created locally by `mj codegen`, under LOCALLY GENERATED
   ids. On such a database the guard looks for an id that is not there, does not
   fire, and inserts a SECOND row for a relationship that already exists.

   There is no unique constraint on (EntityID, RelatedEntityID,
   RelatedEntityJoinField) to catch it, so the duplicate is silent. Its visible
   effect is a doubled related-entity tab on the four affected forms
   (MJ: Entities, MJ: Users, MJ: Identity Claim Types, MJ: Magic Link Invites).

   Verified against a database holding the rows under different ids: the guard
   does not fire, and no unique index exists on the natural key.

   WHY A SEPARATE MIGRATION RATHER THAN A FIX IN PLACE
   ---------------------------------------------------
   V202609091200 is already merged and applied. Editing it would change its
   Flyway checksum and break every database that has run it. A forward-only
   cleanup is the only safe shape.

   A fresh database is unaffected — nothing duplicated, so this is a no-op there.
   ============================================================================ */

DECLARE @IdentityClaimsEntityID UNIQUEIDENTIFIER = '58C8C895-E3AA-48C2-BA68-808337235873';

;WITH ranked AS (
    SELECT
        [ID],
        ROW_NUMBER() OVER (
            PARTITION BY [EntityID], [RelatedEntityID], [RelatedEntityJoinField]
            ORDER BY [__mj_CreatedAt] ASC, [ID] ASC
        ) AS rn
    FROM [${flyway:defaultSchema}].[EntityRelationship]
    WHERE [RelatedEntityID] = @IdentityClaimsEntityID
)
DELETE FROM [${flyway:defaultSchema}].[EntityRelationship]
WHERE [ID] IN (SELECT [ID] FROM ranked WHERE rn > 1);
