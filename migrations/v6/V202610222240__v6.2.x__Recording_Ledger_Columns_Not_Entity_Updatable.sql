-- WHY THIS EXISTS. The seven recording-ledger columns of AIAgentSession (RecordingStatus,
-- RecordingExpectedShards, RecordingCapturedSamples, RecordingGaps, RecordingAssemblyVersion,
-- RecordingFileID, RecordingMedia) are written by the ledger's stored procedures while a session is
-- live (V202610151535__v6.2.x__Realtime_Recording_Shard_Ledger.sql). A session copy loaded before one
-- of those procs ran and saved after it (the close, a heartbeat) sent `@<Field>_Clear=1` for every
-- column that was NULL in memory, so spUpdateAIAgentSession wiped the terminal stamp: a complete
-- recording was deferred and forced to Partial 90 s later. The old guard lived in an entity subclass
-- (MJAIAgentSessionEntityServer.Save), which an app that registers its own session class replaces.
--
