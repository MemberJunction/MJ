-- sets AllowUpdateAPI=0 on the seven fields, so CodeGen leaves them (and their _Clear companions) out of
-- spUpdateAIAgentSession below, and no entity class can write them. RecordingStartedAt stays updatable.
--
-- The two legitimate writers of RecordingFileID / RecordingMedia (the end-of-call upload and the
-- recording-start stamp) now call spStampAIAgentSessionRecordingFile, defined here. Same style as the
-- other ledger procs: one statement, granted to the runtime roles, which hold no table-level DML.
