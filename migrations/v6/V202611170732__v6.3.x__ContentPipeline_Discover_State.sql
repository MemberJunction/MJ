-- =====================================================================================
-- Content pipeline: a Discover walk can stop and carry on in its next run
--
-- A source too large to walk in one run (a long website crawl, a big API listing) had
-- either to finish in one go or start again from the top every time. A driver may now
-- stop part-way (when the walk's time budget, Options.Tuning DiscoverWalkBudgetMs, runs
-- out) and return a resume token; the next walk receives it and carries on from there.
--
-- This column holds that state between runs, as JSON:
--   ResumeToken    The driver's token: where the walk stopped.
--   WalkStartedAt  When the walk's first part started. LastDiscoveredAt takes it once the
--                  walk finishes, so a page changed while the walk was in progress is
--                  still seen as changed by the next walk.
--   Mode           'Discover' or 'Sync'. A walk resumes only in the mode it started in.
--   ItemsFound     Items the walk's earlier parts found.
-- NULL means no walk is in progress. Until the walk finishes the source stays due:
-- ForceDiscovery stays set and LastDiscoveredAt / LastSyncedAt are not moved.
-- =====================================================================================

ALTER TABLE ${flyway:defaultSchema}.ContentSource
ADD DiscoverState NVARCHAR(MAX) COLLATE SQL_Latin1_General_CP1_CI_AS NULL;
GO

