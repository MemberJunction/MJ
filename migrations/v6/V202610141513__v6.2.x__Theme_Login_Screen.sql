-- =============================================================================
-- Theme sign-in page design (Login Studio)
-- =============================================================================
-- The Explorer login screen can be themed, rearranged and extended by a host
-- application (the --mj-login-* tokens, the Login* inputs on <mj-explorer-app>,
-- and the mjLoginSlot templates), but only in code. These two columns let an
-- administrator design it as data instead, in the Login Studio app.
--
-- A sign-in page belongs to a brand, so it lives on the Theme: the default
-- Active theme's published design is what anonymous visitors see, and its logo
-- variants are what a design's logo blocks draw.
--
--   * LoginScreen       the PUBLISHED design. Served unauthenticated by
--                       GET /auth/login-screen, because it is drawn before
--                       anyone signs in. NULL = the stock login screen.
--   * LoginScreenDraft  the design being edited. Never served publicly, so an
--                       administrator can arrange a page without visitors
--                       seeing it half-finished.
--
-- Both hold the JSON document defined by @memberjunction/theme-engine
-- (login-design.ts). The MJ: Themes server entity refuses any document that
-- normalizing would change, so nothing reaches the public route that the
-- contract does not name.
-- =============================================================================

