-- =============================================================================
-- MJ: Graph Concepts gain Origin ('Declared' | 'Inferred'), matching MJ: Graph Edges.
--
-- A concept the Content Pipeline synthesizes from document chunks can quote any of
-- them, so the graph engine's provenance policy shows it only to someone who can
-- read its sources (its SourcedFrom edges). A concept a person authored has no
-- SourcedFrom edges and is visible to anyone who can read concepts.
--
-- Without Origin those two cases are indistinguishable once a synthesized concept
-- loses its last source: a re-indexed or deleted document retracts its chunks'
-- edges, and the orphaned concept would then read as authored and become visible
-- to everyone. Origin keeps the distinction: an Inferred concept with no visible
-- source stays hidden.
--
-- Backfill: every existing concept that is the source of a SourcedFrom edge was
-- synthesized by the pipeline, so it is marked Inferred.
-- =============================================================================

ALTER TABLE [${flyway:defaultSchema}].[GraphConcept] ADD
    [Origin] NVARCHAR(20) COLLATE SQL_Latin1_General_CP1_CI_AS NOT NULL
        CONSTRAINT [DF_GraphConcept_Origin] DEFAULT (N'Declared'),
    CONSTRAINT [CK_GraphConcept_Origin] CHECK ([Origin] IN (N'Declared', N'Inferred'));
GO

UPDATE c
   SET c.[Origin] = N'Inferred'
  FROM [${flyway:defaultSchema}].[GraphConcept] AS c
 WHERE EXISTS (
        SELECT 1
          FROM [${flyway:defaultSchema}].[GraphEdge] AS e
          INNER JOIN [${flyway:defaultSchema}].[GraphEdgeType] AS t ON t.[ID] = e.[EdgeTypeID]
          INNER JOIN [${flyway:defaultSchema}].[Entity] AS en ON en.[ID] = e.[SourceEntityID]
         WHERE t.[Name] = N'SourcedFrom'
           AND en.[Name] = N'MJ: Graph Concepts'
           AND e.[SourceRecordID] = CONVERT(NVARCHAR(400), c.[ID])
       );
