-- =====================================================================================
-- ToolCallingMode gains 'NativeRecovered' (issue #5847)
--
-- Groq checks tool-call arguments against the declared schema and rejects a call whose
-- types do not match (HTTP 400, code tool_use_failed), although MJ's argument coercion
-- would accept it. The rejection still holds the call, and the Groq driver now hands it
-- back instead of failing. 'NativeRecovered' records those turns, so run history can tell
-- them apart from calls the provider accepted ('Native') and from envelope retries
-- ('NativeFallback').
-- =====================================================================================

ALTER TABLE ${flyway:defaultSchema}.AIPromptRun
    DROP CONSTRAINT CK_AIPromptRun_ToolCallingMode;
GO

ALTER TABLE ${flyway:defaultSchema}.AIPromptRun
    ADD CONSTRAINT CK_AIPromptRun_ToolCallingMode
    CHECK (ToolCallingMode IN ('Native', 'Envelope', 'NativeFallback', 'NativeImplicit', 'NativeRecovered'));
GO

