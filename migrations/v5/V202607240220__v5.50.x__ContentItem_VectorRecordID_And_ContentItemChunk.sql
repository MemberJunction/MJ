/*
    ContentItem vector-tracking + ContentItemChunk entity

    ContentItem gains:
      - VectorRecordID: the identifier of the item's vector record in the vector database
        (e.g. Pinecone) when embedded as a single vector — traceability from item to stored vector.
      - ParentID: optional self-FK to another Content Item, enabling a parent/child hierarchy.
      - DisplayLink: optional display/clickable URL, distinct from the ingestion URL.

    New ContentItemChunk entity — makes each embedded chunk of a Content Item's text a
    first-class row so vectors can be traced back to the specific portion of the parent item:
      - ContentItemID (FK), Sequence (ordinal), Text (the embedded chunk), VectorRecordID.
      - EmbeddingStatus / TaggingStatus (NOT NULL, default 'Pending'; value list = ContentItem's
        Complete/Failed/Pending/Processing/Skipped plus 'Active' and 'Processed').
      - DeleteStatus (nullable: NULL = not slated for deletion, 'Pending' = vector deletion queued,
        'Deleted' = vector removed from the vector DB).
      - LastEmbeddedAt / LastTaggedAt / LastDeletedAt tracking timestamps.

    NOTE: Entity/EntityField metadata, the vwContentItems/vwContentItemChunks views, the
    spCreate/spUpdate/spDelete procedures, permissions, and the CodeGen-managed
    CreatedAt/UpdatedAt timestamp columns + FK auto-indexes are all generated by `mj codegen`
    after this migration runs. This file contains hand-written DDL only.
*/

