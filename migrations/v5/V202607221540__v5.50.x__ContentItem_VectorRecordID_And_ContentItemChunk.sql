/*
    ContentItem vector-tracking enhancements

    Part 1 — Persist the vector-database record identifier on ContentItem.
      When a Content Item's text is embedded and upserted into the vector database
      (Pinecone, etc.), the embedding is stored under a specific record id. MemberJunction
      previously never persisted that id, so there was no way to trace a Content Item back
      to its stored vector. VectorRecordID captures it (for items embedded as a single vector).

    Part 2 — Introduce the ContentItem Chunk entity.
      AutotagBaseEngine.VectorizeContentItems chunks a Content Item's text and creates several
      vectors that all link back to the same Content Item, with no record of WHICH portion of
      the item each vector represents. ContentItemChunk makes each chunk a first-class row: it
      links to the parent Content Item, records the chunk's ordinal Sequence, the chunk Text
      that was embedded, and the identifier of that chunk's vector record in the vector database.

    NOTE: Entity/EntityField metadata, the vwContentItemChunks view, the
    spCreate/spUpdate/spDelete procedures, permissions, and CodeGen-managed
    __mj timestamp columns + FK auto-indexes are all generated by `mj codegen`
    after this migration runs. This file contains hand-written DDL only.
*/

-------------------------------------------------------------------------------
-- Part 1: ContentItem.VectorRecordID
-------------------------------------------------------------------------------
ALTER TABLE ${flyway:defaultSchema}.ContentItem ADD
    VectorRecordID NVARCHAR(100) NULL;
GO

-------------------------------------------------------------------------------
-- Part 2: ContentItemChunk table
-------------------------------------------------------------------------------
CREATE TABLE ${flyway:defaultSchema}.ContentItemChunk (
    ID UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID(),
    ContentItemID UNIQUEIDENTIFIER NOT NULL,
    Sequence INT NOT NULL,
    Text NVARCHAR(MAX) NOT NULL,
    VectorRecordID NVARCHAR(100) NULL,
    CONSTRAINT PK_ContentItemChunk PRIMARY KEY (ID),
    CONSTRAINT FK_ContentItemChunk_ContentItemID FOREIGN KEY (ContentItemID) REFERENCES ${flyway:defaultSchema}.ContentItem(ID),
    CONSTRAINT UQ_ContentItemChunk_ContentItemID_Sequence UNIQUE (ContentItemID, Sequence)
);
GO

