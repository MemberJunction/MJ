-- ContentItemChunk — relax Text, add segmentation columns (single ALTER each)
--
-- Text is relaxed to NULL so a media-only segment can persist. Existing rows are
-- unaffected: every chunk written to date carries text.
-------------------------------------------------------------------------------
ALTER TABLE ${flyway:defaultSchema}.ContentItemChunk
    ALTER COLUMN Text NVARCHAR(MAX) NULL;
GO

ALTER TABLE ${flyway:defaultSchema}.ContentItemChunk ADD
    Modality NVARCHAR(20) NOT NULL CONSTRAINT DF_ContentItemChunk_Modality DEFAULT 'text',
    StartOffset INT NULL,
    EndOffset INT NULL,
    StartMs INT NULL,
    EndMs INT NULL,
    PageNumber INT NULL,
    SegmentTitle NVARCHAR(500) NULL,
    Description NVARCHAR(MAX) NULL,
    Transcript NVARCHAR(MAX) NULL,
    SegmenterKey NVARCHAR(100) NULL,
    ParentChunkID UNIQUEIDENTIFIER NULL;
GO

ALTER TABLE ${flyway:defaultSchema}.ContentItemChunk
    ADD CONSTRAINT CK_ContentItemChunk_Modality
        CHECK (Modality IN ('audio','image','multimodal','text','video'));
GO

ALTER TABLE ${flyway:defaultSchema}.ContentItemChunk
    ADD CONSTRAINT FK_ContentItemChunk_ParentChunkID
        FOREIGN KEY (ParentChunkID) REFERENCES ${flyway:defaultSchema}.ContentItemChunk(ID);
GO

