/*
    ContentItemChunk — multimodal segmentation columns

    Extends the chunk entity so a chunk can represent a segment of ANY modality, not just a
    span of text, and so a media chunk carries a readable representation alongside its vector.

    Background: chunks are produced by the pluggable segmentation strategies in
    @memberjunction/ai-segmentation (StructuralText / SemanticText / Transcript / FixedWindow).
    A ContentSegment produced by those strategies carries modality, position (character offsets
    for text, time offsets for audio/video, page number for paginated sources), an optional
    title, and an optional parent for chapter -> sub-chapter hierarchies. Today none of that has
    anywhere to land, so every segment is flattened back to plain text on write.

    Design notes:

      - ONE VECTOR PER CHUNK. VectorRecordID stays a single column: a media chunk stores the
        native multimodal vector and nothing else. Description/Transcript are readable text on
        the row (hydrated at retrieval, rerankable, lexically indexable) — NOT a second
        embedding. This preserves the Chunk-Identity Contract that makes soft-delete + purge
        safe. If a description vector is ever warranted for a corpus, it belongs as a SIBLING
        chunk row (Modality='text', ParentChunkID pointing at the media chunk), never as a
        second vector id on this row.

      - Text becomes NULLABLE. It is currently NOT NULL, which is the single schema blocker
        preventing a pure-media segment (an image, or a video window with no transcript) from
        being persisted at all. Everything downstream keys off VectorRecordID rather than Text,
        so the existing lifecycle carries over unchanged.

      - ParentChunkID is a self-FK, mirroring ContentItem.ParentID, and expresses the
        chapter -> sub-chapter relationship a transcript segmenter produces.

    NOTE: Entity/EntityField metadata, value-list rows for the Modality CHECK constraint, the
    regenerated vwContentItemChunks view, spCreate/spUpdate/spDelete, permissions, FK
    auto-indexes, and the CodeGen-managed timestamp columns are all generated by `mj codegen`
    after this migration runs. This section contains hand-written DDL only.
*/

