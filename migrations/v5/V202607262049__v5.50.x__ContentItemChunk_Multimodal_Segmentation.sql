    Modality NVARCHAR(20) NOT NULL CONSTRAINT DF_ContentItemChunk_Modality DEFAULT 'text',
    StartOffset INT NULL,
    EndOffset INT NULL,
    StartMs INT NULL,
    EndMs INT NULL,
    PageNumber INT NULL,
    SegmentTitle NVARCHAR(500) NULL,
