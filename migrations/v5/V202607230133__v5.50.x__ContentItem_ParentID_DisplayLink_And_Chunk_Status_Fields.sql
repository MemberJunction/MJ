/*
    ContentItem + ContentItemChunk field additions

    Part 1 — ContentItem gets a self-referencing parent and a display link.
      - ParentID: optional self-FK to another Content Item, enabling a parent/child
        hierarchy of content items (e.g. a document and its sub-pages).
      - DisplayLink: an optional display/clickable URL for the item.

    Part 2 — ContentItemChunk gains status-lifecycle + tracking fields, mirroring the
