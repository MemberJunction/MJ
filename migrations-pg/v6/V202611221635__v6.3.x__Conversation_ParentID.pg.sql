CREATE OR REPLACE FUNCTION "__mj"."spDeleteConversation"(
    p_id UUID
) RETURNS TABLE("ID" UUID) AS $$
#variable_conflict use_column
DECLARE
    v_affected_count INTEGER;
    v_rec RECORD;
BEGIN
    -- Cascade: Set MJ: AI Agent Examples.SourceConversationID to NULL
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."AIAgentExample" WHERE "SourceConversationID" = p_id
    LOOP
        UPDATE "__mj"."AIAgentExample" SET "SourceConversationID" = NULL WHERE "ID" = v_rec."ID";
    END LOOP;

    -- Cascade: Set MJ: AI Agent Notes.SourceConversationID to NULL
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."AIAgentNote" WHERE "SourceConversationID" = p_id
    LOOP
        UPDATE "__mj"."AIAgentNote" SET "SourceConversationID" = NULL WHERE "ID" = v_rec."ID";
    END LOOP;

    -- Cascade: Set MJ: AI Agent Runs.ConversationID to NULL
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."AIAgentRun" WHERE "ConversationID" = p_id
    LOOP
        UPDATE "__mj"."AIAgentRun" SET "ConversationID" = NULL WHERE "ID" = v_rec."ID";
    END LOOP;

    -- Cascade: Set MJ: AI Agent Sessions.ConversationID to NULL
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."AIAgentSession" WHERE "ConversationID" = p_id
    LOOP
        UPDATE "__mj"."AIAgentSession" SET "ConversationID" = NULL WHERE "ID" = v_rec."ID";
    END LOOP;

    -- Cascade: Delete MJ: Agent Channels records via ID (only when AgentChannel table exists in PG)
    IF to_regclass('__mj."AgentChannel"') IS NOT NULL THEN
        FOR v_rec IN
            EXECUTE 'SELECT "ID" FROM "__mj"."AgentChannel" WHERE "ID" = $1' USING p_id
        LOOP
            EXECUTE 'SELECT "__mj"."spDeleteAgentChannel"($1)' USING v_rec."ID";
        END LOOP;
    END IF;

    -- Cascade: Delete MJ: Comments records via ID
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."Comment" WHERE "ID" = p_id
    LOOP
        PERFORM "__mj"."spDeleteComment"(v_rec."ID");
    END LOOP;

    -- Cascade: Delete MJ: Conversation Artifacts records via ConversationID
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."ConversationArtifact" WHERE "ConversationID" = p_id
    LOOP
        PERFORM "__mj"."spDeleteConversationArtifact"(v_rec."ID");
    END LOOP;

    -- Cascade: Delete MJ: Conversation Branches records via ConversationID
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."ConversationBranch" WHERE "ConversationID" = p_id
    LOOP
        PERFORM "__mj"."spDeleteConversationBranch"(v_rec."ID");
    END LOOP;

    -- Cascade: Delete MJ: Conversation Details records via ConversationID
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."ConversationDetail" WHERE "ConversationID" = p_id
    LOOP
        PERFORM "__mj"."spDeleteConversationDetail"(v_rec."ID");
    END LOOP;

    -- Cascade: Delete MJ: Conversation Skills records via ConversationID
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."ConversationSkill" WHERE "ConversationID" = p_id
    LOOP
        PERFORM "__mj"."spDeleteConversationSkill"(v_rec."ID");
    END LOOP;

    -- Cascade: Set MJ: Conversations.LastConversationID to NULL
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."Conversation" WHERE "LastConversationID" = p_id
    LOOP
        UPDATE "__mj"."Conversation" SET "LastConversationID" = NULL WHERE "ID" = v_rec."ID";
    END LOOP;

    -- Cascade: Set MJ: Conversations.ParentID to NULL
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."Conversation" WHERE "ParentID" = p_id
    LOOP
        UPDATE "__mj"."Conversation" SET "ParentID" = NULL WHERE "ID" = v_rec."ID";
    END LOOP;

    -- Cascade: Set MJ: Meetings.ConversationID to NULL
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."Meeting" WHERE "ConversationID" = p_id
    LOOP
        UPDATE "__mj"."Meeting" SET "ConversationID" = NULL WHERE "ID" = v_rec."ID";
    END LOOP;

    -- Cascade: Set MJ: User Routines.ConversationID to NULL
    FOR v_rec IN
        SELECT "ID" FROM "__mj"."UserRoutine" WHERE "ConversationID" = p_id
    LOOP
        UPDATE "__mj"."UserRoutine" SET "ConversationID" = NULL WHERE "ID" = v_rec."ID";
    END LOOP;

    DELETE FROM "__mj"."Conversation" WHERE "ID" = p_id;
    GET DIAGNOSTICS v_affected_count = ROW_COUNT;

    IF v_affected_count = 0 THEN
        RETURN QUERY SELECT NULL::UUID AS "ID";
    ELSE
        RETURN QUERY SELECT p_id AS "ID";
    END IF;
END;
$$ LANGUAGE plpgsql;
