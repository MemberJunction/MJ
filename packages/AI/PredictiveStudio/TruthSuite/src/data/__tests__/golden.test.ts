import { describe, it, expect } from 'vitest';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { DatasetCatalog } from '../catalog';
import { GoldenHashes } from '../golden';

/** A seed directory holding the given rows.csv and truth.csv text. */
function seedDir(rows: string, truth: string): string {
  const dir = mkdtempSync(path.join(tmpdir(), 'truth-golden-unit-'));
  writeFileSync(path.join(dir, 'rows.csv'), rows);
  writeFileSync(path.join(dir, 'truth.csv'), truth);
  return dir;
}

describe('GoldenHashes', () => {
  const w1 = DatasetCatalog.Find('world', 'W1-signal');
  const t3lag = DatasetCatalog.Find('scenario', 'T3-lag');

  it('pins every base seed, T3-lag included, and nothing else', () => {
    expect(GoldenHashes.Expected(w1, 42)).not.toBeNull();
    expect(GoldenHashes.Expected(t3lag, 2208)).not.toBeNull();
    expect(GoldenHashes.Expected(DatasetCatalog.Find('world', 'W2-noise'), 150)).toBeNull(); // a t2 seed: no pin
  });

  it('refuses a base seed whose generated bytes differ from the pin', () => {
    expect(() => GoldenHashes.Verify(w1, 42, seedDir('ID\n1\n', 'ID\n1\n'))).toThrow(/rows\.csv .* golden-hashes\.json pins/);
  });

  it('does not check a seed without a pin', () => {
    expect(() => GoldenHashes.Verify(DatasetCatalog.Find('world', 'W2-noise'), 150, seedDir('ID\n', 'ID\n'))).not.toThrow();
  });
});

describe('cache key inputs', () => {
  it('hashes the worlds domain into every world, and the scenario generator into T3-lag', () => {
    for (const code of ['W1-signal', 'W9-multiclass']) {
      expect(DatasetCatalog.Find('world', code).ExtraInputs).toContain('fixtures/worlds-domain/domain.json');
    }
    expect(DatasetCatalog.Find('scenario', 'T3-lag').ExtraInputs).toContain('src/generators/make_scenario.ts');
  });
});
