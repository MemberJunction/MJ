/**
 * Synthetic SQL Server corpus entries (no template tags; templated entries live in `templates.ts`).
 *
 * Every table, view and column name here is invented for the tests. Nothing is copied from a client
 * system.
 */
import type { CorpusEntry } from './types.js';

function ss(Id: string, Tags: string[], SQL: string): CorpusEntry {
    return { Id: `ss/${Id}`, Dialect: 'sqlserver', SQL, Tags };
}

