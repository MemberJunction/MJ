/**
 * Phase G — Dependencies (Install + Build)
 *
 * Runs the configured package manager's `install` at the repo root to install
 * all workspace dependencies, then `run build` to compile all ~170 packages
 * in the monorepo. The package manager defaults to pnpm (the era-6 platform
 * manifest declares pnpm); npm remains available as an explicit override.
 *
 * Key behaviors:
 * - **Workspace scaffold**: pins the root `packageManager` field, rewrites
 *   npm-layout-specific scripts, and (for pnpm) writes `pnpm-workspace.yaml`
 *   when the extracted bundle doesn't ship one.
 * - **ERESOLVE retry (npm only)**: If `npm install` fails with peer dependency
 *   conflicts, automatically retries with `--legacy-peer-deps`. pnpm has no
 *   equivalent flag and treats peer conflicts as warnings, so no retry exists.
 * - **Partial build tolerance**: Build failures in codegen-managed packages
 *   (entity forms, bootstrap) are treated as partial success since CodeGen
 *   will regenerate their source and rebuild in a later phase.
 * - **Audit warnings**: npm vulnerability reports are logged as informational
 *   warnings — users are explicitly told NOT to run `npm audit fix --force`.
 *
 * @module phases/DependencyPhase
 * @see CodeGenPhase — handles rebuilding codegen-managed packages after code generation.
 * @see PlatformCompatPhase — patches scripts before this phase runs.
 */

import type { InstallerEventEmitter } from '../events/InstallerEvents.js';
import { InstallerError } from '../errors/InstallerError.js';
import { ProcessRunner, type ProcessResult } from '../adapters/ProcessRunner.js';
import { FileSystemAdapter } from '../adapters/FileSystemAdapter.js';
import { PackageManagerCommands, type PackageManagerType } from '../models/PackageManager.js';
import path from 'node:path';

/**
 * Convert an install tag into a valid npm version spec.
 *
 * Handles:
 *   - `v5.38.0` / `5.38.0` → `5.38.0`
 *   - `v5.38.0-beta.1` → `5.38.0-beta.1`
 *   - `v5.38.0+meta` → `5.38.0+meta`
 *   - Anything else (branch ref, commit SHA, the literal string `latest`, etc.) → `latest`
 *
 * Without this guard, a branch ref like `feature/some-branch` lands in
 * package.json as `"@memberjunction/cli": "feature/some-branch"`, which npm
 * interprets as a GitHub shorthand and tries to ssh-clone
 * `github.com/feature/some-branch.git`. That hard-fails the install for
 * anyone running `mj install --tag <branch>` (testing/dev scenarios, or
 * users picking a branch ref via the version picker post-fallback).
 *
 * Exported for unit testing; consumed by `DependencyPhase.ensureCliDependency`
 * and `DependencyPhase.ensureHoistedDependencies`.
 */
export function tagToNpmVersion(tag: string): string {
  const stripped = tag.startsWith('v') ? tag.slice(1) : tag;
  return /^\d+\.\d+\.\d+(-[\w.-]+)?(\+[\w.-]+)?$/.test(stripped) ? stripped : 'latest';
}

/**
 * Packages that contain generated code managed by CodeGen.
 *
 * Build failures in **only** these packages are treated as partial success.
 * CodeGen will regenerate their stale source code and rebuild them in the
 * codegen phase. If any package outside this list fails, the build is a
 * hard error.
 */
const CODEGEN_MANAGED_PACKAGES = [
  'mj_generatedentities',
  'mj_generatedactions',
  'ng-core-entity-forms',
  'server-bootstrap-lite',
  'server-bootstrap',
  'ng-bootstrap',
];

/**
 * The `pnpm-workspace.yaml` written into a distribution install when the
 * extracted bundle doesn't ship one (bundles built before the pnpm flip).
 *
 * Both settings are load-bearing under pnpm 10:
 * - `linkWorkspacePackages: true` — without it, exact-version internal deps
 *   resolve from the REGISTRY instead of linking the local workspace package.
 *   For unpublished packages (mj_generatedentities) that fails loudly; for
 *   published ones it silently installs a stale copy.
 * - `onlyBuiltDependencies` — pnpm 10 does not run dependency build scripts
 *   unless allowlisted; anything omitted installs without its postinstall
 *   step and fails later at runtime. The list mirrors the MJ monorepo's own
 *   allowlist for the dependency graph the published packages pull in.
 */
const PNPM_WORKSPACE_YAML = `# Generated by mj install — pnpm workspace definition for the MJ distribution.
packages:
  - 'apps/*'
  - 'packages/*'

# pnpm 10 defaults this to false, which makes exact-version internal deps
# resolve from the registry instead of linking the local workspace package.
linkWorkspacePackages: true

# pnpm 10 only runs dependency build scripts that are allowlisted here.
onlyBuiltDependencies:
  - '@apollo/protobufjs'
  - '@google/genai'
  - '@parcel/watcher'
  - browser-tabs-lock
  - core-js
  - core-js-pure
  - esbuild
  - isolated-vm
  - lmdb
  - msgpackr-extract
  - oracledb
  - protobufjs
  - rete
  - sharp
  - tesseract.js
`;

/**
 * Input context for the dependency phase.
 *
 * @see DependencyPhase.Run
 */
export interface DependencyContext {
  /** Absolute path to the repo root (where install and build are executed). */
  Dir: string;
  /** MemberJunction version tag (e.g., `"v5.9.0"`) — used to pin the CLI dependency version. */
  Tag: string;
  /** Package manager to install and build with (`'pnpm'` default, `'npm'` override). */
  PackageManager: PackageManagerType;
  /** Event emitter for progress, warn, and log events. */
  Emitter: InstallerEventEmitter;
}

/**
 * Result of the dependency phase.
 *
 * @see DependencyPhase.Run
 */
export interface DependencyResult {
  /** Whether the install completed successfully. */
  InstallSuccess: boolean;
  /** Whether the build completed fully (`false` if partial). */
  BuildSuccess: boolean;
  /**
   * Whether the build was partial — codegen-managed packages failed
   * but all other packages succeeded. CodeGen will fix these.
   */
  BuildPartial: boolean;
  /** Non-fatal warnings collected during install and build (e.g., npm audit advisories). */
  Warnings: string[];
}

/**
 * Phase G — Installs workspace dependencies and builds all workspace packages
 * with the configured package manager.
 *
 * @example
 * ```typescript
 * const deps = new DependencyPhase();
 * const result = await deps.Run({ Dir: '/path/to/install', Tag: 'v6.1.0', PackageManager: 'pnpm', Emitter: emitter });
 * if (result.BuildPartial) {
 *   console.log('Partial build — CodeGen will fix remaining packages');
 * }
 * ```
 */
export class DependencyPhase {
  private processRunner = new ProcessRunner();
  private fileSystem = new FileSystemAdapter();

  /**
   * Execute the dependency phase: workspace scaffold, install, then build.
   *
   * @param context - Dependency input with directory, package manager, and emitter.
   * @returns Install/build status and collected warnings.
   * @throws {InstallerError} With code `INSTALL_FAILED` or `INSTALL_TIMEOUT` on install failure.
   * @throws {InstallerError} With code `BUILD_FAILED` or `BUILD_TIMEOUT` on non-codegen build failure.
   */
  async Run(context: DependencyContext): Promise<DependencyResult> {
    const { Emitter: emitter } = context;
    const pm = new PackageManagerCommands(context.PackageManager);
    const warnings: string[] = [];

    // Step 0a: Ensure @memberjunction/cli is a dependency so `mj` in scripts
    // resolves to the correct version (not a stale global install)
    await this.ensureCliDependency(context.Dir, context.Tag, emitter);

    // Step 0b (npm only): Ensure packages that must be hoisted to root node_modules
    // are listed as root dependencies. npm may nest them under workspace packages
    // due to peer-dep conflicts, causing duplicate class instances and Angular DI
    // failures. pnpm's isolated linker doesn't have that nesting problem.
    if (pm.Name === 'npm') {
      await this.ensureHoistedDependencies(context.Dir, context.Tag, emitter);
    }

    // Step 0c: Align the workspace scaffold with the configured package manager
    // (root packageManager pin, PM-neutral scripts, pnpm-workspace.yaml).
    await this.ensurePackageManagerScaffold(context.Dir, pm, emitter);

    // Record the version that will ACTUALLY run the install. Probed in the
    // install dir AFTER the pin is written, because corepack shims and pnpm
    // 10's manage-package-manager-versions resolve the packageManager field
    // by cwd — a preflight PATH probe can report a different version.
    await this.logEffectiveVersion(context.Dir, pm, emitter);

    // Step 1: install
    await this.runInstall(context.Dir, pm, emitter, warnings);

    // Step 2: build
    const buildPartial = await this.runBuild(context.Dir, pm, emitter, warnings);

    return {
      InstallSuccess: true,
      BuildSuccess: !buildPartial,
      BuildPartial: buildPartial,
      Warnings: warnings,
    };
  }

  // ---------------------------------------------------------------------------
  // Install
  // ---------------------------------------------------------------------------

  /**
   * Run the package manager's install. For npm, retries with
   * `--legacy-peer-deps` on ERESOLVE errors — pnpm reports peer conflicts as
   * warnings and has no equivalent flag, so it gets a single attempt.
   * Collects vulnerability warnings into the supplied array.
   */
  private async runInstall(
    dir: string,
    pm: PackageManagerCommands,
    emitter: InstallerEventEmitter,
    warnings: string[]
  ): Promise<void> {
    emitter.Emit('step:progress', {
      Type: 'step:progress',
      Phase: 'dependencies',
      Message: `Running ${pm.Name} install (this may take several minutes)...`,
    });

    let result = await this.runInstallOnce(dir, pm, emitter, []);

    if (result.TimedOut) {
      throw this.installTimeoutError(pm, []);
    }

    // npm only: retry peer dependency conflicts with --legacy-peer-deps
    if (pm.Name === 'npm' && result.ExitCode !== 0 && this.isEresolveError(result.Stderr)) {
      result = await this.retryNpmPeerConflicts(dir, pm, emitter, warnings);
    }

    if (result.ExitCode !== 0) {
      const lastLines = this.lastNLines(result.Stderr || result.Stdout, 50);
      throw new InstallerError(
        'dependencies',
        'INSTALL_FAILED',
        `${pm.Name} install failed (exit code ${result.ExitCode}):\n${lastLines}`,
        `Run "${pm.Name} install" manually at the repo root to see full error output.`
      );
    }

    this.collectAuditWarnings(result.Stderr, pm, emitter, warnings);

    emitter.Emit('log', {
      Type: 'log',
      Level: 'info',
      Message: `${pm.Name} install completed successfully.`,
    });
  }

  /**
   * npm-only ERESOLVE recovery: retry the install with `--legacy-peer-deps`.
   * pnpm has no equivalent flag (it reports peer conflicts as warnings), so
   * this is never reached for pnpm.
   */
  private async retryNpmPeerConflicts(
    dir: string,
    pm: PackageManagerCommands,
    emitter: InstallerEventEmitter,
    warnings: string[]
  ): Promise<ProcessResult> {
    emitter.Emit('warn', {
      Type: 'warn',
      Phase: 'dependencies',
      Message: 'Peer dependency conflict detected. Retrying with --legacy-peer-deps...',
    });

    const result = await this.runInstallOnce(dir, pm, emitter, ['--legacy-peer-deps']);

    if (result.TimedOut) {
      throw this.installTimeoutError(pm, ['--legacy-peer-deps']);
    }

    if (result.ExitCode === 0) {
      warnings.push(
        'npm install required --legacy-peer-deps due to peer dependency conflicts in the release. ' +
        'This is safe but indicates a minor version skew in the release packages.'
      );
    }

    return result;
  }

  /** Surface dependency-audit advisories as informational warnings. */
  private collectAuditWarnings(
    stderr: string,
    pm: PackageManagerCommands,
    emitter: InstallerEventEmitter,
    warnings: string[]
  ): void {
    if (!stderr.includes('vulnerabilit')) {
      return;
    }
    warnings.push(
      `${pm.Name} reports vulnerabilities in dependencies. This is common in large workspaces. ` +
      'Do NOT run "npm audit fix --force" — it can break the workspace.'
    );
    emitter.Emit('warn', {
      Type: 'warn',
      Phase: 'dependencies',
      Message: `${pm.Name} reports dependency vulnerabilities (informational). Do not run "npm audit fix --force".`,
    });
  }

  /**
   * Log the package-manager version resolved from the install directory —
   * the version that actually runs the install (gate-4 evidence). A probe
   * failure is logged and never fails the install; the preflight PATH check
   * already guaranteed the binary exists.
   */
  private async logEffectiveVersion(
    dir: string,
    pm: PackageManagerCommands,
    emitter: InstallerEventEmitter
  ): Promise<void> {
    try {
      const version = await this.processRunner.RunSimple(pm.Name, ['--version'], dir);
      emitter.Emit('log', {
        Type: 'log',
        Level: 'info',
        Message: `Using ${pm.Name} ${version.trim()} for this install (root packageManager pin: ${pm.PackageManagerPin}).`,
      });
    } catch (err) {
      emitter.Emit('log', {
        Type: 'log',
        Level: 'verbose',
        Message: `Could not probe the effective ${pm.Name} version: ${err instanceof Error ? err.message : String(err)}`,
      });
    }
  }

  /** Build the INSTALL_TIMEOUT error for a (possibly retried) install. */
  private installTimeoutError(pm: PackageManagerCommands, extraArgs: string[]): InstallerError {
    const commandLine = [pm.Name, 'install', ...extraArgs].join(' ');
    return new InstallerError(
      'dependencies',
      'INSTALL_TIMEOUT',
      `${commandLine} timed out after 15 minutes.`,
      `Run "${commandLine}" manually at the repo root. Check network connectivity.`
    );
  }

  // ---------------------------------------------------------------------------
  // Build
  // ---------------------------------------------------------------------------

  /**
   * Runs the build script. Returns true if the build was "partial" (only codegen-managed
   * packages failed), false if it fully succeeded. Throws on hard failures.
   */
  private async runBuild(
    dir: string,
    pm: PackageManagerCommands,
    emitter: InstallerEventEmitter,
    warnings: string[]
  ): Promise<boolean> {
    emitter.Emit('step:progress', {
      Type: 'step:progress',
      Phase: 'dependencies',
      Message: `Running ${pm.Name} run build (first-time builds can take 15-20 minutes for 170 packages)...`,
    });

    const build = pm.RunScript('build');
    const result = await this.processRunner.Run(build.Cmd, build.Args, {
      Cwd: dir,
      TimeoutMs: 1_800_000, // 30 minutes — first-time full workspace build of 170 packages can take 17+ min
      OnStdout: (line: string) => {
        emitter.Emit('step:progress', {
          Type: 'step:progress',
          Phase: 'dependencies',
          Message: line.trim(),
        });
      },
      OnStderr: (line: string) => {
        emitter.Emit('log', {
          Type: 'log',
          Level: 'verbose',
          Message: `[build:stderr] ${line.trim()}`,
        });
      },
    });

    if (result.TimedOut) {
      throw new InstallerError(
        'dependencies',
        'BUILD_TIMEOUT',
        `${pm.Name} run build timed out after 30 minutes.`,
        `Run "${pm.Name} run build" manually at the repo root to see full output. First-time builds of 170 packages can take 15-20 minutes.`
      );
    }

    if (result.ExitCode === 0) {
      emitter.Emit('log', {
        Type: 'log',
        Level: 'info',
        Message: 'Build completed successfully.',
      });
      return false;
    }

    // Build failed — check if failures are only in codegen-managed packages.
    // These packages contain generated code that may be stale in the release.
    // CodeGen will regenerate them and rebuild in a later phase.
    // Note: turbo outputs the "Failed:" summary to stdout, not stderr.
    const combinedOutput = result.Stdout + '\n' + result.Stderr;
    const failedPackages = this.extractFailedTurboPackages(combinedOutput);
    const onlyCodegenFailures = failedPackages.length > 0
      && failedPackages.every(pkg => CODEGEN_MANAGED_PACKAGES.some(pattern => pkg.includes(pattern)));

    if (onlyCodegenFailures) {
      const failList = failedPackages.join(', ');
      emitter.Emit('warn', {
        Type: 'warn',
        Phase: 'dependencies',
        Message: `Build partially succeeded. Failed packages (${failList}) contain generated code that will be regenerated by CodeGen.`,
      });
      warnings.push(
        `Build partially succeeded. The following packages failed due to stale generated code and will be fixed by CodeGen: ${failList}`
      );
      return true;
    }

    // Non-codegen failures — hard error
    const lastLines = this.lastNLines(result.Stderr || result.Stdout, 50);
    throw new InstallerError(
      'dependencies',
      'BUILD_FAILED',
      `Build failed (exit code ${result.ExitCode}):\n${lastLines}`,
      `Run "${pm.Name} run build" manually at the repo root to see full error output.`
    );
  }

  // ---------------------------------------------------------------------------
  // Turbo output parsing
  // ---------------------------------------------------------------------------

  /**
   * Extract failed package names from turbo's output.
   *
   * Turbo outputs lines like:
   * - `"Failed:    @memberjunction/ng-core-entity-forms#build"` (scoped)
   * - `"Failed:    mj_generatedactions#build"` (unscoped)
   *
   * @param output - Combined stdout + stderr from turbo.
   * @returns Deduplicated list of failed package names.
   */
  private extractFailedTurboPackages(output: string): string[] {
    const packages: string[] = [];
    const failedPattern = /Failed:\s+([@\w][^#\s]*)#build/g;
    let match: RegExpExecArray | null;
    while ((match = failedPattern.exec(output)) !== null) {
      packages.push(match[1]);
    }
    return [...new Set(packages)];
  }

  // ---------------------------------------------------------------------------
  // Helpers
  // ---------------------------------------------------------------------------

  /**
   * Execute a single install invocation with optional extra arguments.
   * Streams stdout/stderr to the emitter for real-time progress.
   */
  private async runInstallOnce(
    dir: string,
    pm: PackageManagerCommands,
    emitter: InstallerEventEmitter,
    extraArgs: string[]
  ): Promise<ProcessResult> {
    const install = pm.Install(extraArgs);
    return this.processRunner.Run(install.Cmd, install.Args, {
      Cwd: dir,
      TimeoutMs: 900_000, // 15 minutes
      OnStdout: (line: string) => {
        emitter.Emit('step:progress', {
          Type: 'step:progress',
          Phase: 'dependencies',
          Message: line.trim(),
        });
      },
      OnStderr: (line: string) => {
        if (line.includes('WARN') || line.includes('warn')) {
          emitter.Emit('log', {
            Type: 'log',
            Level: 'verbose',
            Message: `[${pm.Name}] ${line.trim()}`,
          });
        }
      },
    });
  }

  /** Check whether npm stderr output indicates an ERESOLVE peer-dependency conflict. */
  private isEresolveError(stderr: string): boolean {
    return stderr.includes('ERESOLVE') || stderr.includes('unable to resolve dependency tree');
  }

  /** Return the last `n` lines of a multi-line string. */
  private lastNLines(text: string, n: number): string {
    const lines = text.split('\n');
    return lines.slice(-n).join('\n');
  }

  // ---------------------------------------------------------------------------
  // CLI dependency injection
  // ---------------------------------------------------------------------------

  /**
   * Ensure `@memberjunction/cli` is in the root `package.json` devDependencies.
   *
   * In monorepo mode, the CLI is already a workspace package. In distribution
   * mode, it needs to be pinned to the correct npm version.
   */
  private async ensureCliDependency(
    dir: string,
    tag: string,
    emitter: InstallerEventEmitter
  ): Promise<void> {
    const pkgPath = path.join(dir, 'package.json');
    const pkg = await this.fileSystem.ReadJSON<Record<string, Record<string, string>>>(pkgPath);

    // If CLI is already a workspace dependency (monorepo), skip version pinning
    const existing = pkg['devDependencies']?.['@memberjunction/cli'] ?? pkg['dependencies']?.['@memberjunction/cli'];
    if (existing && (existing.startsWith('workspace:') || existing.startsWith('file:'))) {
      return;
    }

    const npmVersion = tagToNpmVersion(tag);

    if (!pkg['devDependencies']) {
      pkg['devDependencies'] = {};
    }

    if (existing === npmVersion) {
      return;
    }

    pkg['devDependencies']['@memberjunction/cli'] = npmVersion;
    await this.fileSystem.WriteJSON(pkgPath, pkg);

    emitter.Emit('step:progress', {
      Type: 'step:progress',
      Phase: 'dependencies',
      Message: `Added @memberjunction/cli@${npmVersion} to devDependencies`,
    });
  }

  // ---------------------------------------------------------------------------
  // Dependency hoisting (npm only)
  // ---------------------------------------------------------------------------

  /**
   * Packages that must be hoisted to the root `node_modules` to avoid duplicate-
   * instance problems with Angular's DI system and MJ's ClassFactory.
   * Only applicable for npm distribution installs — pnpm's isolated linker
   * never nests a package under a workspace member the way npm hoisting can.
   */
  private static readonly HOISTED_PACKAGES: ReadonlyArray<{
    Name: string;
    Section: 'dependencies' | 'devDependencies';
  }> = [
    { Name: '@memberjunction/ng-auth-services', Section: 'dependencies' },
  ];

  /**
   * Ensure packages that require hoisting are listed in the root package.json.
   * In monorepo mode, workspace resolution handles this automatically.
   */
  private async ensureHoistedDependencies(
    dir: string,
    tag: string,
    emitter: InstallerEventEmitter
  ): Promise<void> {
    // Check if this is a monorepo layout — if so, skip hoisting
    const monorepoMarker = path.join(dir, 'packages', 'MJCoreEntities');
    if (await this.fileSystem.DirectoryExists(monorepoMarker)) {
      return;
    }

    const pkgPath = path.join(dir, 'package.json');
    const pkg = await this.fileSystem.ReadJSON<Record<string, Record<string, string>>>(pkgPath);
    const npmVersion = tagToNpmVersion(tag);

    let modified = false;

    for (const { Name, Section } of DependencyPhase.HOISTED_PACKAGES) {
      if (!pkg[Section]) {
        pkg[Section] = {};
      }

      const existing = pkg[Section][Name];
      if (existing === npmVersion) {
        continue;
      }

      pkg[Section][Name] = npmVersion;
      modified = true;

      emitter.Emit('step:progress', {
        Type: 'step:progress',
        Phase: 'dependencies',
        Message: `Added ${Name}@${npmVersion} to ${Section} (hoisting fix)`,
      });
    }

    if (modified) {
      await this.fileSystem.WriteJSON(pkgPath, pkg);
    }
  }

  // ---------------------------------------------------------------------------
  // Package-manager scaffold
  // ---------------------------------------------------------------------------

  /**
   * Align the extracted workspace with the configured package manager:
   * pin the root `packageManager` field, rewrite npm-layout scripts to
   * PM-neutral forms, and (pnpm only) write `pnpm-workspace.yaml` when the
   * bundle doesn't ship one. Runs on every install so bundles built before
   * the pnpm flip install correctly too.
   */
  private async ensurePackageManagerScaffold(
    dir: string,
    pm: PackageManagerCommands,
    emitter: InstallerEventEmitter
  ): Promise<void> {
    await this.patchRootManifest(dir, pm, emitter);

    if (pm.Name === 'pnpm') {
      await this.ensurePnpmWorkspaceFile(dir, emitter);
    }
  }

  /** Pin `packageManager` and neutralize npm-layout scripts in the root manifest. */
  private async patchRootManifest(
    dir: string,
    pm: PackageManagerCommands,
    emitter: InstallerEventEmitter
  ): Promise<void> {
    const pkgPath = path.join(dir, 'package.json');
    const pkg = await this.fileSystem.ReadJSON<Record<string, unknown>>(pkgPath);
    let modified = false;

    if (pkg['packageManager'] !== pm.PackageManagerPin) {
      pkg['packageManager'] = pm.PackageManagerPin;
      modified = true;
    }

    const scripts = (pkg['scripts'] ?? {}) as Record<string, string>;

    // The `mj*` scripts historically pointed at apps/MJAPI/node_modules — an
    // npm-hoisting artifact that doesn't exist under pnpm. The CLI is a root
    // devDependency (ensureCliDependency), so its bin is on every script's
    // PATH under both package managers.
    const npmHoistPath = 'node_modules/@memberjunction/cli';
    const mjScriptRewrites: Record<string, string> = {
      'mj': 'mj',
      'mj:migrate': 'mj migrate',
      'mj:codegen': 'mj codegen',
    };
    for (const [name, replacement] of Object.entries(mjScriptRewrites)) {
      if (scripts[name]?.includes(npmHoistPath)) {
        scripts[name] = replacement;
        modified = true;
      }
    }

    const installDeps = `${pm.Name} install`;
    if (scripts['install:deps'] && scripts['install:deps'] !== installDeps) {
      scripts['install:deps'] = installDeps;
      modified = true;
    }

    // Pre-flip bundles route `build` through npm (`npm run build:stream`) and
    // carry npm-only guidance in prebuild/setup. Rewrite those exact shim
    // forms to PM-neutral equivalents so a pnpm install never shells back
    // into npm; anything user-customized is left alone.
    if (scripts['build'] === 'npm run build:stream') {
      scripts['build'] = 'turbo --log-order=stream build';
      modified = true;
    }
    if (scripts['prebuild']?.includes('Run: npm install')) {
      scripts['prebuild'] =
        'node -e "try { require.resolve(\'turbo\') } catch (e) { console.error(\'\\n❌ Dependencies not installed. Run: pnpm install (or npm install)\\n\'); process.exit(1); }"';
      modified = true;
    }
    if (scripts['setup']?.includes('npm run mj:migrate')) {
      scripts['setup'] = "echo 'Please run the mj:migrate, mj:codegen, and build scripts with your package manager.'";
      modified = true;
    }

    if (!modified) {
      return;
    }

    pkg['scripts'] = scripts;
    await this.fileSystem.WriteJSON(pkgPath, pkg);
    emitter.Emit('step:progress', {
      Type: 'step:progress',
      Phase: 'dependencies',
      Message: `Pinned root packageManager to ${pm.PackageManagerPin}`,
    });
  }

  /** Write `pnpm-workspace.yaml` when the extracted bundle doesn't ship one. */
  private async ensurePnpmWorkspaceFile(dir: string, emitter: InstallerEventEmitter): Promise<void> {
    const wsPath = path.join(dir, 'pnpm-workspace.yaml');
    if (await this.fileSystem.FileExists(wsPath)) {
      return;
    }

    await this.fileSystem.WriteText(wsPath, PNPM_WORKSPACE_YAML);
    emitter.Emit('step:progress', {
      Type: 'step:progress',
      Phase: 'dependencies',
      Message: 'Wrote pnpm-workspace.yaml (bundle predates the pnpm flip)',
    });
  }
}
