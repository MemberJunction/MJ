import { describe, it, expect } from 'vitest';
import { Component, Input } from '@angular/core';
import { renderComponentFixture, query, text, hasClass, attr, useFakeGlobalProvider } from '@memberjunction/ng-test-utils';
import { DatabasePreviewPaneComponent } from './database-preview-pane.component';
import type { EntityTableSpec } from '../../database-designer.types';

/**
 * DOM coverage for <mj-database-preview-pane> (module-declared, OnPush) — a live preview of the
 * wizard draft with two tabs (Diagram / SQL). The Diagram tab renders <mj-erd-diagram>; the SQL tab
 * renders <mj-code-editor> bound to the derived DDL. We stub both children (lightweight standalone)
 * and assert: the tab switcher, active-tab styling + aria-selected, which child shows per tab, and
 * that the SQL child receives DDL derived from the TableDefinition (table name + preview comment).
 * `TableDefinition` is a setter @Input that recomputes on set. `new Metadata()` is reached inside
 * satellite-field resolution (only when ForeignKeys exist) — we install a fake global provider with
 * no entities so that path is inert. Tab switch is a real click event (drives OnPush re-render).
 */

@Component({ standalone: true, selector: 'mj-erd-diagram', template: '<div class="erd-stub"></div>' })
class ErdStub {
  @Input() nodes: unknown; @Input() focusNodeId: unknown; @Input() focusDepth = 1;
  @Input() readOnly = false; @Input() showHeader = false; @Input() config: unknown;
}
@Component({ standalone: true, selector: 'mj-code-editor', template: '<pre class="code-stub">{{ value }}</pre>' })
class CodeEditorStub {
  @Input() value = ''; @Input() language = ''; @Input() readonly = false;
  @Input() lineWrapping = false; @Input() setup = '';
}

const spec = (over: Partial<EntityTableSpec> = {}): Partial<EntityTableSpec> =>
  ({ EntityName: 'Members', SchemaName: 'crm', TableName: 'Member', Columns: [], ForeignKeys: [], ...over });

const render = (TableDefinition: Partial<EntityTableSpec> | null) =>
  renderComponentFixture(DatabasePreviewPaneComponent, {
    imports: [ErdStub, CodeEditorStub],
    declarations: [DatabasePreviewPaneComponent],
    inputs: { TableDefinition },
  });

describe('DatabasePreviewPaneComponent (DOM)', () => {
  const install = useFakeGlobalProvider();

  it('renders both preview tabs', () => {
    install({ entities: [] });
    const fixture = render(spec());
    const tabs = fixture.nativeElement.querySelectorAll('.preview-tab');
    expect(tabs.length).toBe(2);
    expect(fixture.nativeElement.textContent).toContain('Diagram');
    expect(fixture.nativeElement.textContent).toContain('SQL');
  });

  it('defaults to the Diagram tab: erd shown, code editor hidden, tab marked active', () => {
    install({ entities: [] });
    const fixture = render(spec());
    expect(query(fixture, 'mj-erd-diagram')).not.toBeNull();
    expect(query(fixture, 'mj-code-editor')).toBeNull();
    const diagramTab = fixture.nativeElement.querySelectorAll('.preview-tab')[0] as HTMLElement;
    expect(diagramTab.classList.contains('active')).toBe(true);
    expect(diagramTab.getAttribute('aria-selected')).toBe('true');
  });

  it('switches to the SQL tab on click: code editor shown, erd hidden', () => {
    install({ entities: [] });
    const fixture = render(spec());
    (fixture.nativeElement.querySelectorAll('.preview-tab')[1] as HTMLElement).click();
    fixture.detectChanges(false);
    expect(query(fixture, 'mj-code-editor')).not.toBeNull();
    expect(query(fixture, 'mj-erd-diagram')).toBeNull();
  });

  it('feeds the SQL editor DDL derived from the TableDefinition', () => {
    install({ entities: [] });
    const fixture = render(spec({ TableName: 'Member', SchemaName: 'crm' }));
    (fixture.nativeElement.querySelectorAll('.preview-tab')[1] as HTMLElement).click();
    fixture.detectChanges(false);
    const sql = text(fixture, '.code-stub');
    expect(sql).toContain('CREATE TABLE [crm].[Member]');
    expect(sql).toContain('Generated by Database Designer');
  });

  it('marks the SQL header as ALTER when IsAlter is set', () => {
    install({ entities: [] });
    const fixture = renderComponentFixture(DatabasePreviewPaneComponent, {
      imports: [ErdStub, CodeEditorStub],
      declarations: [DatabasePreviewPaneComponent],
      inputs: { TableDefinition: spec(), IsAlter: true },
    });
    (fixture.nativeElement.querySelectorAll('.preview-tab')[1] as HTMLElement).click();
    fixture.detectChanges(false);
    expect(text(fixture, '.code-stub')).toContain('ALTER');
  });
});
