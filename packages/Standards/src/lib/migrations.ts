/**
 * @fileoverview Finding the migrations a migration standard should read, and the part of each
 * one a person wrote.
 *
 * Two facts shape everything here:
 *
 * - **Migrations are immutable once applied.** A standard adopted today cannot ask anyone to edit a
 *   migration that already ran, so every migration check takes a `FromVersion` cutoff and reads
 *   only migrations at or after it.
 * - **Half of a migration is generated.** By MJ convention, CodeGen's output is appended below the
 *   hand-written DDL after a run of blank lines and a banner. That generated half legitimately uses
 *   patterns a person must not (CodeGen guards its own `DROP VIEW` with `IF OBJECT_ID`), so a
 *   migration check reads only the hand-written half.
 *
 * @module @memberjunction/standards
 */

import { readFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';
import { FindSourceFiles } from './walk.js';

/** One migration file, split at the hand-written / generated boundary. */
export interface MigrationFile {
    /** Repo-relative path. */
    File: string;
    /** The 12-digit timestamp from the file name (`V202610201300__…` gives `202610201300`). */
    Version: string;
    /** Every line of the file, unmodified. Marker lookups need the original text. */
    Lines: string[];
    /** How many leading lines are hand-written. Lines after this belong to CodeGen. */
    HandWrittenLineCount: number;
}

/**
 * A blank-line run this long ends the hand-written section. The convention asks for at least 50;
 * a lower bar tolerates a trimmed separator without mistaking ordinary spacing for one.
 */
export const SEPARATOR_BLANK_LINES = 20;

/** Banner lines CodeGen output starts with, any one of which ends the hand-written section. */
const CODEGEN_BANNERS: readonly RegExp[] = [/GENERATED BY MemberJunction CodeGen/i, /This was generated by the MemberJunction CodeGen tool/i];

/** The header CodeGen writes above each statement it emits: `/* SQL text to add special date field … *\/`. */
const CODEGEN_STATEMENT_HEADER = /^\s*\/\*\s*SQL (?:generated|text) to\b/i;

/** Directory names a migration walk never descends into. PostgreSQL output is converter-owned. */
const SKIP_DIRS: ReadonlySet<string> = new Set(['node_modules', '.git', 'dist', 'migrations-pg', 'codegen']);

/** A versioned migration: `V` + 12-digit timestamp + `__`. Repeatable and baseline files are skipped. */
const VERSIONED = /^V(\d{12})__.+\.sql$/i;

/**
 * The number of hand-written lines at the top of a migration: everything before the first long
 * run of blank lines or the first CodeGen banner, whichever comes first. A file with neither is
 * all hand-written.
 */
export function HandWrittenLineCount(lines: readonly string[]): number {
    let blankRun = 0;
    for (let i = 0; i < lines.length; i++) {
        const line = lines[i];
        if (CODEGEN_BANNERS.some((b) => b.test(line))) return i;
        if (line.trim() === '') {
            blankRun++;
            if (blankRun >= SEPARATOR_BLANK_LINES) return i - blankRun + 1;
        } else {
            blankRun = 0;
        }
    }
    return lines.length;
}

/**
 * Did CodeGen write the statement that starts on `line` (1-based)? True when the nearest non-blank
 * line above it is one of CodeGen's statement headers.
 *
 * This recognizes CodeGen output pasted without the separator one statement at a time, rather than
 * ending the hand-written section at the first header: older migrations put CodeGen output first and
 * hand-written DDL after it, and that DDL still has to be read.
 */
export function IsCodeGenStatement(lines: readonly string[], line: number): boolean {
    for (let i = line - 2; i >= 0; i--) {
        if (lines[i].trim() === '') continue;
        return CODEGEN_STATEMENT_HEADER.test(lines[i]);
    }
    return false;
}

/**
 * Comment-free copies of `lines`, the same length and line-for-line, so a pattern inside a
 * `--` or block comment never counts as code. Quoted strings are kept: a status value lives in one.
 */
export function StripSqlComments(lines: readonly string[]): string[] {
    const out: string[] = [];
    let inBlock = false;
    for (const line of lines) {
        let result = '';
        let inString = false;
        for (let i = 0; i < line.length; i++) {
            const ch = line[i];
            const next = line[i + 1];
            if (inBlock) {
                if (ch === '*' && next === '/') {
                    inBlock = false;
                    i++;
                }
                continue;
            }
            if (inString) {
                result += ch;
                if (ch === "'") inString = false;
                continue;
            }
            if (ch === "'") {
                inString = true;
                result += ch;
            } else if (ch === '-' && next === '-') {
                break;
            } else if (ch === '/' && next === '*') {
                inBlock = true;
                i++;
            } else {
                result += ch;
            }
        }
        out.push(result);
    }
    return out;
}

/**
 * Every versioned migration under `roots` whose timestamp is at or after `fromVersion`.
 *
 * `fromVersion` is the 12-digit timestamp a repo adopted the standard at. An empty or malformed
 * value reads nothing and says so in a note, rather than reading the whole history: flagging
 * migrations that can no longer be edited would teach a repo to switch the check off.
 */
export function FindMigrations(repoRoot: string, roots: readonly string[], fromVersion: string): { Migrations: MigrationFile[]; Notes: string[] } {
    if (!/^\d{12}$/.test(fromVersion)) {
        return {
            Migrations: [],
            Notes: [`FromVersion must be a 12-digit migration timestamp (got "${fromVersion}"); no migrations were read.`],
        };
    }
    const migrations: MigrationFile[] = [];
    for (const root of roots) {
        // A root can name a skipped directory itself (`migrations-pg`), which the walk's own
        // skip set never sees, since that set only stops it descending.
        if (SKIP_DIRS.has(basename(root))) continue;
        const files = FindSourceFiles(join(repoRoot, root), { SkipDirs: SKIP_DIRS, Extensions: ['.sql'], Exclude: (f) => f.endsWith('.pg.sql') });
        for (const full of files) {
            const match = VERSIONED.exec(basename(full));
            if (!match || match[1] < fromVersion) continue;
            const lines = readFileSync(full, 'utf8').split(/\r?\n/);
            migrations.push({ File: relative(repoRoot, full), Version: match[1], Lines: lines, HandWrittenLineCount: HandWrittenLineCount(lines) });
        }
    }
    migrations.sort((a, b) => a.File.localeCompare(b.File));
    return { Migrations: migrations, Notes: [] };
}
