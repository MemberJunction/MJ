import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { FindMigrations, HandWrittenLineCount, StripSqlComments } from '../lib/migrations.js';
import { FindExistenceGuards, MigrationExistenceGuardsCheck } from '../checks/migration-existence-guards.js';
import { FindCheckListValues, IsMachineStyle, ReadableForm, ReadableStatusValuesCheck } from '../checks/readable-status-values.js';
import { FindUncollatedStringColumns, MigrationStringCollationCheck } from '../checks/migration-string-collation.js';

const SEPARATOR = Array.from({ length: 50 }, () => '').join('\n');

describe('HandWrittenLineCount', () => {
    it('ends the hand-written part at the blank-line separator', () => {
        const lines = ['CREATE TABLE A (ID INT);', ...SEPARATOR.split('\n'), 'IF OBJECT_ID(N\'vwA\') IS NOT NULL DROP VIEW vwA;'];
        expect(HandWrittenLineCount(lines)).toBe(1);
    });

    it('ends the hand-written part at a CodeGen banner', () => {
        const lines = ['ALTER TABLE A ADD B INT;', '/** GENERATED BY MemberJunction CodeGen - DO NOT EDIT BY HAND **/', 'IF OBJECT_ID(N\'x\') IS NOT NULL DROP VIEW x;'];
        expect(HandWrittenLineCount(lines)).toBe(1);
    });

    it('treats a file with neither as all hand-written', () => {
        expect(HandWrittenLineCount(['a', '', 'b'])).toBe(3);
    });
});

describe('StripSqlComments', () => {
    it('blanks line and block comments, keeps strings, preserves line count', () => {
        const out = StripSqlComments(["SELECT 'a -- not a comment' -- real comment", '/* IF OBJECT_ID(', ') */ SELECT 1']);
        expect(out).toEqual(["SELECT 'a -- not a comment' ", '', ' SELECT 1']);
    });
});

describe('FindExistenceGuards', () => {
    it('flags catalog-function guards', () => {
        expect(FindExistenceGuards(["IF COL_LENGTH(N'[s].[T]', N'C') IS NULL", "IF OBJECT_ID(N'[s].[T]', N'U') IS NULL", 'IF NOT (OBJECT_ID(N\'x\') IS NULL)'])).toEqual([1, 2, 3]);
    });

    it('flags IF [NOT] EXISTS over the catalog, including extended properties, across lines', () => {
        const code = ['IF NOT EXISTS (', "    SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_X')", "IF NOT EXISTS (SELECT 1 FROM sys.fn_listextendedproperty(N'MS_Description', NULL, NULL, NULL, NULL, NULL, NULL))"];
        expect(FindExistenceGuards(code)).toEqual([1, 3]);
    });

    it('flags IF [NOT] EXISTS over a bracketed catalog name', () => {
        const code = ["IF NOT EXISTS (SELECT 1 FROM [sys].[columns] WHERE Name = N'X')", "IF EXISTS (SELECT 1 FROM [INFORMATION_SCHEMA].[COLUMNS] WHERE COLUMN_NAME = N'X')"];
        expect(FindExistenceGuards(code)).toEqual([1, 2]);
    });

    it('flags DROP … IF EXISTS', () => {
        expect(FindExistenceGuards(['DROP INDEX IF EXISTS IX_A ON T;', 'DROP SEQUENCE IF EXISTS s.Seq;', 'DROP SYNONYM IF EXISTS s.Syn;'])).toEqual([1, 2, 3]);
    });

    it('leaves temp-table cleanup alone', () => {
        expect(FindExistenceGuards(["IF OBJECT_ID('tempdb..#uef') IS NOT NULL DROP TABLE #uef;", 'DROP TABLE IF EXISTS #work;'])).toEqual([]);
    });

    it('leaves IF EXISTS over ordinary data alone', () => {
        expect(FindExistenceGuards(["IF EXISTS (SELECT 1 FROM [s].[Deal] WHERE Status = N'Old')", "    UPDATE [s].[Deal] SET Status = N'New';"])).toEqual([]);
    });

    it('leaves plain DDL alone', () => {
        expect(FindExistenceGuards(['ALTER TABLE T ADD C INT NULL;', 'CREATE TABLE U (ID UNIQUEIDENTIFIER);'])).toEqual([]);
    });
});

describe('ReadableForm / IsMachineStyle', () => {
    it('spots run-together and snake_case values and rewrites them', () => {
        expect(IsMachineStyle('OptedIn')).toBe(true);
        expect(IsMachineStyle('NOT_SPECIFIED')).toBe(true);
        expect(ReadableForm('NotSpecified')).toBe('Not Specified');
        expect(ReadableForm('opted_out')).toBe('Opted Out');
    });

    it('leaves readable and single-word values alone', () => {
        for (const value of ['Opted In', 'Active', 'SMS', 'Not Specified', 'Email']) expect(IsMachineStyle(value)).toBe(false);
    });
});

describe('FindCheckListValues', () => {
    it('reads a single-line IN list, with N prefixes', () => {
        const values = FindCheckListValues(["CONSTRAINT CK_A CHECK (Status IN (N'Opted In', N'OptedOut'))"]).map((v) => v.Value);
        expect(values).toEqual(['Opted In', 'OptedOut']);
    });

    it('reads a list that spans lines and reports each value on its own line', () => {
        const values = FindCheckListValues(['CHECK (Status IN (', "    'Draft',", "    'InReview'", '))']);
        expect(values).toEqual([
            { Line: 2, Value: 'Draft' },
            { Line: 3, Value: 'InReview' },
        ]);
    });

    it('ignores a CHECK without an IN list, and never reaches into a later statement', () => {
        const code = ['CONSTRAINT CK_Amount CHECK (Amount >= 0),', 'GO', "UPDATE T SET X = 1 WHERE Y IN ('NotACheckValue');"];
        expect(FindCheckListValues(code)).toEqual([]);
    });

    it('unescapes doubled quotes', () => {
        expect(FindCheckListValues(["CHECK (Reason IN ('Customer''s Request'))"]).map((v) => v.Value)).toEqual(["Customer's Request"]);
    });
});

describe('FindUncollatedStringColumns', () => {
    const lines = (sql: string): number[] => FindUncollatedStringColumns(sql.split('\n')).map((c) => c.Line);

    it('flags an unpinned string column in CREATE TABLE and passes a pinned one', () => {
        const sql = [
            'CREATE TABLE [${flyway:defaultSchema}].[Persona] (',
            '    ID UNIQUEIDENTIFIER NOT NULL DEFAULT NEWSEQUENTIALID(),',
            '    Name NVARCHAR(255) NOT NULL,',
            '    Code VARCHAR(20) COLLATE SQL_Latin1_General_CP1_CI_AS NOT NULL,',
            "    Kind NCHAR(1) NOT NULL DEFAULT 'a, b',",
            '    Body NVARCHAR(MAX) COLLATE SQL_Latin1_General_CP1_CI_AS NULL,',
            '    CONSTRAINT UQ_Persona_Name UNIQUE (Name)',
            ');',
        ].join('\n');
        expect(FindUncollatedStringColumns(sql.split('\n'))).toEqual([
            { Line: 3, Column: 'Name', Type: 'NVARCHAR' },
            { Line: 5, Column: 'Kind', Type: 'NCHAR' },
        ]);
    });

    it('reads bracketed names and types, and leaves non-string columns and computed columns alone', () => {
        const sql = 'CREATE TABLE s.T ([Display Name] [nvarchar](50) NULL, Total DECIMAL(18,2), Label AS (CAST(Total AS NVARCHAR(20))), Charge INT);';
        expect(FindUncollatedStringColumns([sql])).toEqual([{ Line: 1, Column: '[Display Name]', Type: 'NVARCHAR' }]);
    });

    it('flags ALTER TABLE … ADD columns, with and without a semicolon, and skips ADD CONSTRAINT', () => {
        const sql = [
            'ALTER TABLE [s].[A] ADD Note NVARCHAR(100) NULL, Pinned NVARCHAR(10) COLLATE SQL_Latin1_General_CP1_CI_AS NULL;',
            'ALTER TABLE [s].[B] ADD',
            '    Label VARCHAR(30) NULL',
            'GO',
            "ALTER TABLE [s].[B] ADD CONSTRAINT DF_B_Label DEFAULT 'x' FOR Label;",
            'ALTER TABLE [s].[C] ADD Code CHAR(2) NULL',
            "EXEC sp_addextendedproperty @name = N'MS_Description', @value = N'Code NVARCHAR text';",
        ].join('\n');
        expect(lines(sql)).toEqual([1, 3, 6]);
    });

    it('exempts table variables and #temp tables', () => {
        const sql = [
            'DECLARE @t TABLE (Name NVARCHAR(50));',
            'CREATE TABLE #work (Name NVARCHAR(50));',
            'CREATE TABLE ##shared (Name NVARCHAR(50));',
            'ALTER TABLE #work ADD Extra NVARCHAR(10) NULL;',
        ].join('\n');
        expect(lines(sql)).toEqual([]);
    });

    it('does not mistake ALTER COLUMN or a CAST for a column definition', () => {
        const sql = ['ALTER TABLE s.A ALTER COLUMN Name NVARCHAR(100) NOT NULL;', 'SELECT CAST(1 AS NVARCHAR(10));'].join('\n');
        expect(lines(sql)).toEqual([]);
    });

    it('reads quoted and spaced multi-part names', () => {
        const sql = ['CREATE TABLE "s"."Q" (Name NVARCHAR(10));', 'ALTER TABLE s . [R] ADD Code NCHAR(2) NULL;'].join('\n');
        expect(lines(sql)).toEqual([1, 2]);
    });

    it('returns quickly on a long name that never closes the statement', () => {
        const started = Date.now();
        FindUncollatedStringColumns(['CREATE TABLE ' + '"!".'.repeat(20000), 'ALTER TABLE ' + '!.'.repeat(20000)]);
        expect(Date.now() - started).toBeLessThan(2000);
    });

    it('ends an ALTER TABLE … ADD at a semicolon, so a later statement\'s COLLATE does not cover it', () => {
        const sql = 'ALTER TABLE a ADD X NVARCHAR(10); ALTER TABLE b ADD Z NVARCHAR(10) COLLATE foo;';
        expect(FindUncollatedStringColumns([sql]).map((c) => c.Column)).toEqual(['X']);
    });

    it('ends an ALTER TABLE … ADD at the next statement keyword when there is no semicolon', () => {
        const sql = ['ALTER TABLE a ADD X NVARCHAR(10) NULL', 'ALTER TABLE b ADD Z NVARCHAR(10) COLLATE foo NULL'];
        expect(FindUncollatedStringColumns(sql).map((c) => c.Column)).toEqual(['X']);
    });

    it('flags a COLLATE other than the expected collation when one is given, compared case-insensitively', () => {
        const sql = [
            'CREATE TABLE s.T (',
            '    A NVARCHAR(10) COLLATE Latin1_General_100_CS_AS NULL,',
            '    B NVARCHAR(10) COLLATE sql_latin1_general_cp1_ci_as NULL,',
            '    C NVARCHAR(10) NULL',
            ');',
        ];
        expect(FindUncollatedStringColumns(sql, 'SQL_Latin1_General_CP1_CI_AS')).toEqual([
            { Line: 2, Column: 'A', Type: 'NVARCHAR', DeclaredCollation: 'Latin1_General_100_CS_AS' },
            { Line: 4, Column: 'C', Type: 'NVARCHAR' },
        ]);
        // Without an expected collation any COLLATE clause passes.
        expect(FindUncollatedStringColumns(sql).map((c) => c.Column)).toEqual(['C']);
    });
});

describe('migration checks against a repo', () => {
    let repo: string;

    const writeMigration = (name: string, body: string): void => {
        mkdirSync(join(repo, 'migrations', 'v6'), { recursive: true });
        writeFileSync(join(repo, 'migrations', 'v6', name), body);
    };

    beforeEach(() => {
        repo = mkdtempSync(join(tmpdir(), 'mj-standards-migrations-'));
    });

    afterEach(() => {
        rmSync(repo, { recursive: true, force: true });
    });

    it('reads only versioned migrations at or after FromVersion, and skips migrations-pg', () => {
        writeMigration('V202610200000__v6.2.x__Old.sql', 'SELECT 1;');
        writeMigration('V202610210100__v6.2.x__New.sql', 'SELECT 1;');
        writeMigration('R__Repeatable.sql', 'SELECT 1;');
        mkdirSync(join(repo, 'migrations-pg', 'v6'), { recursive: true });
        writeFileSync(join(repo, 'migrations-pg', 'v6', 'V202610210200__v6.2.x__Pg.pg.sql'), 'SELECT 1;');
        const { Migrations } = FindMigrations(repo, ['migrations', 'migrations-pg'], '202610210000');
        expect(Migrations.map((m) => m.Version)).toEqual(['202610210100']);
    });

    it('reads nothing, with a note, when FromVersion is missing or malformed', () => {
        writeMigration('V202610210100__v6.2.x__New.sql', "IF OBJECT_ID(N'x') IS NULL CREATE TABLE x (ID INT);");
        const result = MigrationExistenceGuardsCheck.Run({ RepoRoot: repo, Roots: ['migrations'], Options: {} });
        expect(result).toMatchObject({ Violations: [] });
        expect((result as { Notes: string[] }).Notes[0]).toMatch(/FromVersion must be a 12-digit/);
    });

    it('flags guards in the hand-written part only, and honors the marker', async () => {
        writeMigration(
            'V202610210100__v6.2.x__Consent.sql',
            [
                "IF COL_LENGTH(N'[s].[ContactType]', N'X') IS NULL",
                '    ALTER TABLE [s].[ContactType] ADD X INT NULL;',
                '-- mj-standards-allow: existence-guard (shared with a repo that predates this table)',
                "IF OBJECT_ID(N'[s].[Legacy]', N'U') IS NULL",
                '    CREATE TABLE [s].[Legacy] (ID INT);',
                SEPARATOR,
                "IF OBJECT_ID(N'[s].[vwContactType]', N'V') IS NOT NULL DROP VIEW [s].[vwContactType];",
            ].join('\n'),
        );
        const result = await MigrationExistenceGuardsCheck.Run({ RepoRoot: repo, Roots: ['migrations'], Options: { FromVersion: '202610210000' } });
        expect(result.Violations.map((v) => v.Line)).toEqual([1]);
    });

    it('skips a CodeGen statement pasted without the separator, and keeps reading the DDL after it', async () => {
        writeMigration(
            'V202610210100__v6.2.x__NoSeparator.sql',
            [
                '/* SQL text to recompile all views */',
                'EXEC [s].spRecompileAllViews',
                '',
                "IF COL_LENGTH(N'[s].[Contact]', N'X') IS NULL",
                '    ALTER TABLE [s].[Contact] ADD X INT NULL;',
                '',
                '/* SQL text to add special date field __mj_CreatedAt to entity s.Contact */',
                "IF COL_LENGTH('[s].[Contact]', '__mj_CreatedAt') IS NULL",
                '    ALTER TABLE [s].[Contact] ADD [__mj_CreatedAt] DATETIMEOFFSET NULL;',
                'GO',
                '',
                '/* SQL text to add default constraint for special date field __mj_CreatedAt */',
                '',
                "IF NOT EXISTS (SELECT 1 FROM sys.default_constraints WHERE [name] = 'DF_Contact_CreatedAt')",
                "    ALTER TABLE [s].[Contact] ADD CONSTRAINT [DF_Contact_CreatedAt] DEFAULT GETUTCDATE() FOR [__mj_CreatedAt];",
            ].join('\n'),
        );
        const result = await MigrationExistenceGuardsCheck.Run({ RepoRoot: repo, Roots: ['migrations'], Options: { FromVersion: '202610210000' } });
        expect(result.Violations.map((v) => v.Line)).toEqual([4]);
    });

    it('flags machine-style CHECK values, honoring AllowedValues and the marker', async () => {
        writeMigration(
            'V202610210100__v6.2.x__Consent.sql',
            [
                'CREATE TABLE [s].[ContactConsent] (',
                "    ConsentStatus NVARCHAR(20) NOT NULL CHECK (ConsentStatus IN (N'NotSpecified', N'Opted In')),",
                "    Provider NVARCHAR(20) NOT NULL CHECK (Provider IN (N'PayPal', N'Stripe')),",
                "    -- mj-standards-allow: status-value (the vendor's own code)",
                "    Code NVARCHAR(20) NOT NULL CHECK (Code IN (N'ACH_DEBIT'))",
                ');',
            ].join('\n'),
        );
        const result = await ReadableStatusValuesCheck.Run({
            RepoRoot: repo,
            Roots: ['migrations'],
            Options: { FromVersion: '202610210000', AllowedValues: ['PayPal'] },
        });
        expect(result.Violations.map((v) => v.Line)).toEqual([2]);
        expect(result.Violations[0].Message).toMatch(/^'NotSpecified' is written for a machine\./);
        expect(result.Violations[0].Message).toContain("'Not Specified'");
    });

    it('flags unpinned string columns in migrations at or after FromVersion only, honoring the marker and the separator', async () => {
        writeMigration('V202611010000__v6.2.x__Before.sql', 'CREATE TABLE [s].[Old] (Name NVARCHAR(50) NOT NULL);');
        writeMigration(
            'V202611030000__v6.2.x__Personas.sql',
            [
                'CREATE TABLE [s].[Persona] (',
                '    Name NVARCHAR(255) NOT NULL,',
                '    -- mj-standards-allow: collation (binary match on an external key)',
                '    ExternalKey VARCHAR(64) NOT NULL',
                ');',
                SEPARATOR,
                'ALTER TABLE [s].[Persona] ADD Generated NVARCHAR(10) NULL;',
            ].join('\n'),
        );
        const result = await MigrationStringCollationCheck.Run({ RepoRoot: repo, Roots: ['migrations'], Options: { FromVersion: '202611020000' } });
        expect(result.Violations.map((v) => [v.File, v.Line])).toEqual([[join('migrations', 'v6', 'V202611030000__v6.2.x__Personas.sql'), 2]]);
        expect(result.Violations[0].Message).toContain('COLLATE SQL_Latin1_General_CP1_CI_AS');
    });

    it('skips only the migrations named in Exempt, and checks a later-merged migration with an older timestamp', async () => {
        const unpinned = 'CREATE TABLE [s].[T] (Name NVARCHAR(50) NOT NULL);';
        writeMigration('V202611030000__v6.2.x__Released.sql', unpinned);
        writeMigration('V202611040751__v6.2.x__Document_Sequence_Counter.sql', unpinned);
        // Dated before the exempt files (written on a branch earlier) but not exempt: still checked.
        writeMigration('V202611020000__v6.3.x__Merged_Later.sql', unpinned);
        writeMigration('V202611100000__v6.3.x__New.sql', 'CREATE TABLE [s].[N] (Name NVARCHAR(50) COLLATE Latin1_General_100_CS_AS NOT NULL);');
        const result = await MigrationStringCollationCheck.Run({
            RepoRoot: repo,
            Roots: ['migrations'],
            Options: {
                FromVersion: '202610210000',
                Collation: 'SQL_Latin1_General_CP1_CI_AS',
                Exempt: ['V202611030000__v6.2.x__Released.sql', 'v202611040751__V6.2.X__document_sequence_counter.sql', 'V202601010000__Gone.sql'],
            },
        });
        expect(result.Violations.map((v) => v.File)).toEqual([
            join('migrations', 'v6', 'V202611020000__v6.3.x__Merged_Later.sql'),
            join('migrations', 'v6', 'V202611100000__v6.3.x__New.sql'),
        ]);
        expect(result.Violations[1].Message).toContain('is COLLATE Latin1_General_100_CS_AS, not SQL_Latin1_General_CP1_CI_AS');
        expect(result.Notes).toContain('2 migration(s) at or after 202610210000 read, 2 exempt.');
        expect(result.Notes?.some((n) => n.includes('v202601010000__gone.sql'))).toBe(true);
    });
});
