/**
 * @fileoverview Data types and contracts for memory note corpus generation and gate measurement.
 *
 * @module @memberjunction/integration-test-suite
 */

import type { MemoryNoteCandidate } from '@memberjunction/ai-agents';

/** The ground-truth classification of an extracted memory note candidate. */
export type CorpusLabel = 'durable' | 'ephemeral' | 'wrong' | 'speculative';

/** Note type in MemoryManagerAgent. */
export type MemoryNoteType = 'Preference' | 'Constraint' | 'Context' | 'Example' | 'Issue';

/** Scope level of memory note. */
export type MemoryNoteScope = 'global' | 'company' | 'user';

/** A candidate note generated with its ground truth label before splitting. */
export interface RawGeneratedCandidate {
    Type: MemoryNoteType;
    ScopeLevel: MemoryNoteScope;
    Content: string;
    Label: CorpusLabel;
}

/** A scenario generated by the LLM during corpus construction. */
export interface RawGeneratedScenario {
    Turns: Array<{ role: 'user' | 'assistant'; text: string }>;
    Notes: RawGeneratedCandidate[];
}

/** A candidate note in corpus.jsonl with its self-reported confidence. */
export interface CorpusNoteCandidate extends MemoryNoteCandidate {
    NoteId: string;
    SelfConfidence: number;
}

/** One scenario in corpus.jsonl. */
export interface CorpusScenario {
    Id: string;
    Excerpt: string;
    Notes: CorpusNoteCandidate[];
}

/** One record in labels.jsonl. */
export interface CorpusLabelRecord {
    NoteId: string;
    Label: CorpusLabel;
}

/** One observation from running the decision gate on a candidate note. */
export interface DecisionObservation {
    ScenarioId: string;
    NoteId: string;
    Rep: number;
    RawProbability: number;
    CalibratedProbability?: number;
    ModelName: string;
    LatencyMs: number;
    CostUsd: number;
    PromptRunId?: string;
}

/** Metrics for an operating point threshold. */
export interface OperatingThresholdMetrics {
    Threshold: number;
    Precision: number | null;
    Recall: number | null;
    F1: number | null;
    KeptShareByLabel: Record<CorpusLabel, number>;
}

/** Arm evaluation result. */
export interface ArmEvaluationResult {
    Name: 'self-confidence' | 'decision-raw' | 'decision-calibrated';
    Auc: number | null;
    AucBootstrapCi?: { Low: number; High: number } | null;
    OperatingPoints: OperatingThresholdMetrics[];
}

/** Complete measurement report structure written to report.json. */
export interface MeasurementReportJson {
    GeneratedAt: string;
    ScenarioCount: number;
    NoteCount: number;
    LabelDistribution: Record<CorpusLabel, number>;
    Models: string[];
    Reps: number;
    FittedPlattByModel: Record<string, { A: number; B: number }>;
    SelfConfidenceArm: ArmEvaluationResult;
    DecisionRawArm: ArmEvaluationResult;
    DecisionCalibratedArm: ArmEvaluationResult;
    Latency: {
        P50Ms: number | null;
        P95Ms: number | null;
    };
    CostPerThousandNotesUsd: number | null;
    RepeatabilityAgreement: number | null;
}
