/**
 * Tests for workspace status collection and rendering
 * (src/lib/dev-workspace/status.ts). Collection runs against temp fixtures;
 * parsing and rendering are pure. The pnpm version is injected — no spawns.
 */
import { afterEach, describe, expect, it } from 'vitest';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { BuildSentinel, BuildWorkspaceYaml } from '../lib/dev-workspace/build.js';
import { CollectWorkspaceStatus, ParseWorkspaceMembers, RenderStatus } from '../lib/dev-workspace/status.js';
import type { WorkspaceStatus } from '../lib/dev-workspace/types.js';
import { CreateFixtureParent, RemoveFixture } from './dev-workspace-fixture.js';

let parent: string | null = null;

afterEach(() => {
  if (parent !== null) RemoveFixture(parent);
  parent = null;
});

/** Minimal workspace-yaml member with the default packages glob. */
function member(name: string, globs: string[] = ['packages/*']): { Name: string; WorkspaceGlobs: string[] } {
  return { Name: name, WorkspaceGlobs: globs };
}

describe('ParseWorkspaceMembers', () => {
  it('round-trips the members out of a generated pnpm-workspace.yaml', () => {
    const yaml = BuildWorkspaceYaml([member('bizapps-tasks'), member('bizapps-common'), member('MJ-repo')]);
    expect(ParseWorkspaceMembers(yaml)).toEqual(['MJ-repo', 'bizapps-common', 'bizapps-tasks']);
  });

  it('ignores the packages globs and the build-scripts allowlist entries', () => {
    const yaml = BuildWorkspaceYaml([member('bizapps-x')]);
    const members = ParseWorkspaceMembers(yaml);
    expect(members).toEqual(['bizapps-x']);
    expect(members).not.toContain('esbuild'); // allowlist entry, different yaml key
  });

  it('still yields only member names when a member contributes nested globs (#3795)', () => {
    const yaml = BuildWorkspaceYaml([member('MJ', ['packages/*', 'packages/AI/*', 'packages/Angular/Explorer/*'])]);
    expect(ParseWorkspaceMembers(yaml)).toEqual(['MJ']);
  });

  it('returns [] for empty input', () => {
    expect(ParseWorkspaceMembers('')).toEqual([]);
  });
});

describe('CollectWorkspaceStatus', () => {
  it('reports nothing generated on a bare parent', () => {
    parent = CreateFixtureParent({ 'bizapps-x': { RootPackageJson: { name: 'x' }, MjAppJson: true } });
    const status = CollectWorkspaceStatus(parent, '10.33.0', 'default');
    expect(status.Files.every((f) => !f.Exists)).toBe(true);
    expect(status.LockfileExists).toBe(false);
    expect(status.NodeModulesExists).toBe(false);
    expect(status.Members).toEqual([]);
    expect(status.DetectedCandidates).toEqual(['bizapps-x']);
    expect(status.CandidatesNotInWorkspace).toEqual(['bizapps-x']);
    expect(status.PinnedPnpm).toBeNull();
    expect(status.ParentIsGitRepo).toBe(false);
    expect(status.Sentinel).toEqual({ Kind: 'absent' });
  });

  it('reads the sentinel when the parent was generated by the tool', () => {
    parent = CreateFixtureParent({ 'bizapps-x': { RootPackageJson: { name: 'x' }, MjAppJson: true } });
    writeFileSync(
      path.join(parent, '.mj-dev-workspace.json'),
      BuildSentinel(['package.json', '.mj-dev-workspace.json'], ['bizapps-x']),
      'utf8'
    );
    const status = CollectWorkspaceStatus(parent, null, 'env');
    expect(status.Sentinel.Kind).toBe('valid');
    expect(status.DirSource).toBe('env');
  });

  it('reports files, members, missing member dirs, and unlisted candidates', () => {
    parent = CreateFixtureParent({
      'bizapps-x': { RootPackageJson: { name: 'x' }, MjAppJson: true },
      'bizapps-y': { RootPackageJson: { name: 'y' }, MjAppJson: true },
    });
    writeFileSync(path.join(parent, 'pnpm-workspace.yaml'), BuildWorkspaceYaml([member('bizapps-x'), member('ghost-repo')]), 'utf8');
    writeFileSync(path.join(parent, 'package.json'), JSON.stringify({ packageManager: 'pnpm@10.33.0' }), 'utf8');
    mkdirSync(path.join(parent, 'node_modules'));

    const status = CollectWorkspaceStatus(parent, '10.33.0', 'flag');
    const existing = status.Files.filter((f) => f.Exists).map((f) => f.Name);
    expect(existing.sort()).toEqual(['package.json', 'pnpm-workspace.yaml']);
    expect(status.NodeModulesExists).toBe(true);
    expect(status.Members).toEqual(['bizapps-x', 'ghost-repo']);
    expect(status.MissingMemberDirs).toEqual(['ghost-repo']);
    expect(status.CandidatesNotInWorkspace).toEqual(['bizapps-y']);
    expect(status.PinnedPnpm).toBe('pnpm@10.33.0');
    expect(status.ActivePnpmVersion).toBe('10.33.0');
  });

  it('rejects a relative parent path', () => {
    expect(() => CollectWorkspaceStatus('relative/dir', null, 'default')).toThrow(/absolute/);
  });

  it('flags a member-root .pnpm store as a standalone install, but not parent-linked node_modules', () => {
    parent = CreateFixtureParent({
      'bizapps-forked': { RootPackageJson: { name: 'forked' }, MjAppJson: true },
      'bizapps-linked': { RootPackageJson: { name: 'linked' }, MjAppJson: true },
      'bizapps-npm': { RootPackageJson: { name: 'npmish' }, MjAppJson: true },
    });
    writeFileSync(
      path.join(parent, 'pnpm-workspace.yaml'),
      BuildWorkspaceYaml([member('bizapps-forked'), member('bizapps-linked'), member('bizapps-npm')]),
      'utf8'
    );
    // forked: pnpm standalone install → member-root local store
    mkdirSync(path.join(parent, 'bizapps-forked', 'node_modules', '.pnpm'), { recursive: true });
    // linked: what a healthy parent install leaves inside a member — node_modules WITHOUT a local store
    mkdirSync(path.join(parent, 'bizapps-linked', 'node_modules'), { recursive: true });
    // npm: npm standalone install → tree marker
    mkdirSync(path.join(parent, 'bizapps-npm', 'node_modules'), { recursive: true });
    writeFileSync(path.join(parent, 'bizapps-npm', 'node_modules', '.package-lock.json'), '{}', 'utf8');

    const status = CollectWorkspaceStatus(parent, null, 'flag');
    expect(status.MembersWithStandaloneInstalls).toEqual(['bizapps-forked', 'bizapps-npm']);
  });
});

/** A fully-populated status literal the render tests mutate per-case. */
function baseStatus(): WorkspaceStatus {
  return {
    ParentDir: '/the/parent',
    DirSource: 'flag',
    ParentIsGitRepo: false,
    MembersWithStandaloneInstalls: [],
    Files: [
      { Name: 'pnpm-workspace.yaml', Exists: true },
      { Name: '.npmrc', Exists: true },
      { Name: 'package.json', Exists: true },
      { Name: 'turbo.json', Exists: false },
    ],
    LockfileExists: true,
    NodeModulesExists: false,
    Members: ['bizapps-x'],
    MissingMemberDirs: [],
    DetectedCandidates: ['bizapps-x', 'bizapps-y'],
    CandidatesNotInWorkspace: ['bizapps-y'],
    Sentinel: {
      Kind: 'valid',
      Sentinel: { generatedBy: 'mj dev workspace', files: ['package.json'], members: ['bizapps-x'] },
    },
    PinnedPnpm: 'pnpm@10.33.0',
    ActivePnpmVersion: '10.33.0',
  };
}

describe('RenderStatus', () => {
  it('shows file presence, members, unlisted candidates, and a pnpm match', () => {
    const report = RenderStatus(baseStatus());
    expect(report).toContain('pnpm-workspace.yaml');
    expect(report).toContain('turbo.json');
    expect(report).toContain('members (1): bizapps-x');
    expect(report).toContain('not in workspace: bizapps-y');
    expect(report).toContain('match');
  });

  it('flags a pnpm pin/active MISMATCH', () => {
    const status = { ...baseStatus(), ActivePnpmVersion: '9.15.0' };
    expect(RenderStatus(status)).toContain('MISMATCH');
  });

  it('flags pnpm not runnable at the parent', () => {
    const status = { ...baseStatus(), ActivePnpmVersion: null };
    expect(RenderStatus(status)).toContain('not runnable');
  });

  it('warns loudly when the parent is itself a git repo root', () => {
    const status = { ...baseStatus(), ParentIsGitRepo: true };
    expect(RenderStatus(status)).toContain('git repo root');
  });

  it('warns per member with a standalone install, naming the fix', () => {
    const status = { ...baseStatus(), MembersWithStandaloneInstalls: ['bizapps-forked'] };
    const out = RenderStatus(status);
    expect(out).toContain('STANDALONE INSTALL: bizapps-forked');
    expect(out).toContain('--clean-members');
  });

  it('reports missing member dirs', () => {
    const status = { ...baseStatus(), Members: ['bizapps-x', 'ghost'], MissingMemberDirs: ['ghost'] };
    expect(RenderStatus(status)).toContain('missing on disk: ghost');
  });

  it('reports a sentinel as proof the workspace came from the generator', () => {
    const report = RenderStatus(baseStatus());
    expect(report).toContain('sentinel: .mj-dev-workspace.json — generated by mj dev workspace');
    expect(report).toContain('members: bizapps-x');
  });

  it('reports an absent sentinel as hand-made or pre-sentinel, and that clean needs --force', () => {
    const status: WorkspaceStatus = { ...baseStatus(), Sentinel: { Kind: 'absent' } };
    const report = RenderStatus(status);
    expect(report).toContain('sentinel: none — hand-made or pre-sentinel workspace');
    expect(report).toContain('clean needs --force');
  });

  it('says how --dir was resolved, for each of the three sources', () => {
    expect(RenderStatus(baseStatus())).toContain('resolved from: --dir flag');
    const fromEnv: WorkspaceStatus = { ...baseStatus(), DirSource: 'env' };
    expect(RenderStatus(fromEnv)).toContain('resolved from: $MJ_DEV_WORKSPACE_DIR');
    const fromDefault: WorkspaceStatus = { ...baseStatus(), DirSource: 'default' };
    expect(RenderStatus(fromDefault)).toContain('resolved from: default (current directory)');
  });

  it('reports a sentinel that is present but not ours, with the reason', () => {
    const status: WorkspaceStatus = {
      ...baseStatus(),
      Sentinel: { Kind: 'invalid', Reason: 'unparseable JSON: bad token' },
    };
    const report = RenderStatus(status);
    expect(report).toContain('present but not ours');
    expect(report).toContain('unparseable JSON: bad token');
  });
});
