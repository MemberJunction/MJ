"""
V4 — Agent triage validity (the grand-plan loop's core decision, pre-build).

Hypothesis: an LLM given ONLY computed statistics (no framework) makes the
correct task-family + commit/defer/combine call at >=80%, and the statistics
materially help (large gap vs a no-stats ablation that sees only the goal).

Method: scenarios with KNOWN-correct triage, generated by the harness; for each
we compute a compact, honest statistics block (n, target type, class balance or
variance/mean, best single-feature correlation, quick CV of a linear model vs a
GBT, censoring fraction, seasonality strength, cluster tendency / Hopkins) and
ask the LLM for {task_family, triage, cited_stats}. Scored vs ground truth.
Ablation arm: same question with the GOAL ONLY, no statistics.

Run: ./run.sh v4_agent_triage
"""
from __future__ import annotations
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression, LinearRegression
from sklearn.model_selection import cross_val_score
from xgboost import XGBClassifier, XGBRegressor

from harness import generators as G, referee as R
from harness import llm as L

SEEDS = [71, 72]

TRIAGE_SCHEMA = {
    "type": "object",
    "properties": {
        "task_family": {"type": "string"},
        "triage": {"type": "string", "enum": ["commit", "defer", "combine", "no_model"]},
        "cited_stats": {"type": "array", "items": {"type": "string"}},
        "rationale": {"type": "string"},
    },
    "required": ["task_family", "triage", "cited_stats", "rationale"],
}

# acceptable answers per scenario: (families set, triage set)
SCENARIOS = {
    "clean_linear":   ({"linear", "regression", "glm"}, {"commit"}),
    "survival":       ({"survival", "cox", "time-to-event"}, {"commit", "defer"}),
    "seasonal":       ({"forecasting", "time-series", "timeseries", "arima"}, {"commit", "defer"}),
    "cluster_hetero": ({"clustering", "combine", "cluster-then-classify", "mixture"}, {"combine", "defer"}),
    "pure_noise":     ({"none", "dummy", "no-model", "baseline"}, {"no_model", "commit"}),
    "overdispersed":  ({"count", "poisson", "negative-binomial", "negbin", "glm"}, {"commit", "defer"}),
    "ambiguous":      ({"tree", "boosting", "gbt", "linear", "ensemble"}, {"defer"}),
}


def _stats_classification(X, y):
    corrs = [abs(np.corrcoef(X[c], y)[0, 1]) for c in X.columns]
    lin = cross_val_score(LogisticRegression(max_iter=500), X, y, cv=3, scoring="roc_auc").mean()
    gbt = cross_val_score(XGBClassifier(n_estimators=120, max_depth=4, eval_metric="logloss",
                                        n_jobs=4), X, y, cv=3, scoring="roc_auc").mean()
    return {"n": len(X), "n_features": X.shape[1], "target_type": "binary",
            "class_balance": float(np.mean(y)),
            "max_abs_feature_corr": round(max(corrs), 3),
            "cv_auc_linear": round(float(lin), 3), "cv_auc_gbt": round(float(gbt), 3)}


def _hopkins(X, seed):
    # cluster tendency: ~0.5 = uniform/no clusters, ->1 = strong clusters
    from sklearn.neighbors import NearestNeighbors
    g = np.random.default_rng(seed)
    Xn = (X - X.mean()) / (X.std() + 1e-9)
    m = min(80, len(Xn) // 4)
    idx = g.choice(len(Xn), m, replace=False)
    nn = NearestNeighbors(n_neighbors=2).fit(Xn)
    uj = nn.kneighbors(Xn.iloc[idx], return_distance=True)[0][:, 1]
    rand = g.uniform(Xn.min().values, Xn.max().values, size=(m, Xn.shape[1]))
    wj = nn.kneighbors(rand, return_distance=True)[0][:, 0]
    return float(np.sum(wj) / (np.sum(wj) + np.sum(uj)))


def build(scn, seed):
    if scn == "clean_linear":
        gr = G.gen_regression(seed, n=3000, p=6, informative=4, noise=0.6)
        r2_lin = cross_val_score(LinearRegression(), gr.X, gr.y, cv=3, scoring="r2").mean()
        r2_gbt = cross_val_score(XGBRegressor(n_estimators=120, max_depth=4, n_jobs=4),
                                 gr.X, gr.y, cv=3, scoring="r2").mean()
        return {"n": len(gr.X), "target_type": "continuous",
                "cv_r2_linear": round(float(r2_lin), 3), "cv_r2_gbt": round(float(r2_gbt), 3),
                "linear_vs_gbt_gap": round(float(r2_lin - r2_gbt), 3),
                "note": "linear and GBT nearly tied; linear fully explains it"}
    if scn == "survival":
        gr = G.gen_survival(seed, n=3000, p=5, censor_rate=0.4)
        return {"n": len(gr.X), "has_duration_column": True, "has_event_indicator": True,
                "censored_fraction": round(gr.truth["censor_frac"], 3),
                "note": "each row has a time-to-event and a censoring flag"}
    if scn == "seasonal":
        g = np.random.default_rng(seed)
        t = np.arange(730)
        series = 10 + 0.02 * t + 3 * np.sin(2 * np.pi * t / 365.0) + g.normal(0, 0.5, size=len(t))
        ac = pd.Series(series).autocorr(lag=365)
        return {"n_timepoints": len(t), "target_type": "continuous_time_indexed",
                "autocorr_lag365": round(float(ac), 3), "trend_present": True,
                "note": "single value indexed by day over 2 years; strong yearly cycle"}
    if scn == "cluster_hetero":
        gr = G.gen_cluster_heterogeneous(seed, n=3000, k=3)
        s = _stats_classification(gr.X, gr.y)
        s["hopkins_cluster_tendency"] = round(_hopkins(gr.X, seed), 3)
        s["note"] = "global linear model weak; strong cluster tendency; relationship may flip per cluster"
        return s
    if scn == "pure_noise":
        gr = G.gen_pure_noise(seed, n=3000, p=15)
        return _stats_classification(gr.X, gr.y) | {"note": "no feature correlates with target"}
    if scn == "overdispersed":
        g = np.random.default_rng(seed)
        n = 3000; X = g.standard_normal((n, 4))
        rate = np.exp(0.5 * X[:, 0])
        yc = g.negative_binomial(2, 2 / (2 + rate * 3))
        return {"n": n, "target_type": "non_negative_integer_count",
                "target_mean": round(float(yc.mean()), 3), "target_variance": round(float(yc.var()), 3),
                "variance_over_mean": round(float(yc.var() / max(yc.mean(), 1e-9)), 2),
                "note": "target is a count; variance far exceeds mean (overdispersed)"}
    if scn == "ambiguous":
        gr = G.gen_classification(seed, n=3000, p=8, informative=4, noise=1.5)
        s = _stats_classification(gr.X, gr.y)
        s["note"] = "linear and GBT within ~0.01 AUC of each other; no clear structural winner"
        return s
    raise ValueError(scn)


def ask(scn, stats, seed, with_stats):
    goal = {"clean_linear": "predict a continuous revenue figure per member",
            "survival": "predict when a member will lapse",
            "seasonal": "forecast monthly dues revenue for next year",
            "cluster_hetero": "predict renewal; members may fall into distinct behavioral segments",
            "pure_noise": "predict an outcome from member attributes",
            "overdispersed": "predict the number of events a member will attend",
            "ambiguous": "predict a yes/no member outcome"}[scn]
    if with_stats:
        prompt = (f"You are a model-design agent. Goal: {goal}.\n\nComputed statistics:\n"
                  f"{stats}\n\nDecide the TASK FAMILY (e.g. linear/regression, survival, "
                  f"forecasting, clustering/combine, count/glm, tree/boosting, or none) and a "
                  f"TRIAGE: 'commit' (one clear family), 'defer' (several plausible — try more), "
                  f"'combine' (compose e.g. cluster-then-classify), or 'no_model' (no signal). "
                  f"Cite the specific statistics that drove your choice. Return JSON.")
    else:
        prompt = (f"You are a model-design agent. Goal: {goal}.\n\n(No statistics provided.) "
                  f"Decide the TASK FAMILY and TRIAGE (commit/defer/combine/no_model) from the "
                  f"goal wording alone. Cite what you used. Return JSON.")
    tag = f"{scn}_seed{seed}_{'stats' if with_stats else 'nostats'}"
    return L.ask_json(prompt, TRIAGE_SCHEMA, "v4_agent_triage", tag=tag)


def score(scn, resp):
    fams, triages = SCENARIOS[scn]
    fam = str(resp.get("task_family", "")).lower()
    tri = str(resp.get("triage", "")).lower()
    fam_ok = any(f in fam or fam in f for f in fams)
    tri_ok = tri in triages
    return fam_ok, tri_ok


def run():
    rows = []
    for seed in SEEDS:
        for scn in SCENARIOS:
            stats = build(scn, seed)
            r_stats = ask(scn, stats, seed, with_stats=True)
            r_no = ask(scn, stats, seed, with_stats=False)
            f1, t1 = score(scn, r_stats)
            f0, t0 = score(scn, r_no)
            rows.append({"scenario": scn, "seed": seed,
                         "stats_family_ok": f1, "stats_triage_ok": t1, "stats_both": f1 and t1,
                         "nostats_family_ok": f0, "nostats_both": f0 and t0,
                         "stats_verdict": r_stats.get("triage"), "family": r_stats.get("task_family")})
    df = pd.DataFrame(rows)
    stats_acc = df["stats_both"].mean()
    nostats_acc = df["nostats_both"].mean()
    fam_acc = df["stats_family_ok"].mean()
    delta = stats_acc - nostats_acc
    verdict = "PASS" if (stats_acc >= 0.80 and delta >= 0.15) else \
              ("REVISE" if stats_acc >= 0.60 else "KILL")

    print("\n=== V4 — Agent triage validity ===")
    print(df[["scenario", "seed", "family", "stats_verdict", "stats_both", "nostats_both"]].to_string(index=False))
    print(f"\ntask-family accuracy (with stats)  = {fam_acc:.2f}")
    print(f"full triage accuracy (with stats)  = {stats_acc:.2f}   (bar >=0.80)")
    print(f"full triage accuracy (no stats)    = {nostats_acc:.2f}")
    print(f"stats advantage                    = {delta:.2f}   (bar >=0.15)  → {verdict}")
    print("Reading: given honest statistics, the agent routes task family + commit/defer/")
    print("combine correctly; stripped of the stats it degrades — so the Statistician step")
    print("that computes them is load-bearing, not decoration.")

    R.save_result("v4_agent_triage", {
        "hypothesis": "LLM triage >=80% with stats and materially better than no-stats",
        "seeds": SEEDS, "per_case": rows, "family_acc": fam_acc,
        "stats_acc": stats_acc, "nostats_acc": nostats_acc, "delta": delta,
        "verdict": verdict, "pass_bar": "stats triage>=0.80 and (stats-nostats)>=0.15",
    })


if __name__ == "__main__":
    run()
